;===============================================================================
; Command tail parsing
;===============================================================================

; Parse one token from command tail.
; Supported values (case-insensitive):
;   PLAIN/0, VT100/1, ANSI/2 -> ERR_OK, ARG_TERM set
;   SHOW                     -> ERR_SHOW
;   VERIFY                   -> ERR_VERIFY
;   (no token)               -> ERR_NO_ARG (interactive mode)
PARSE_MODE_ARG:
	LD	HL, $0080
	LD	B, (HL)
	INC	HL

PARSE_SKIP_SPACES:
	LD	A, B
	OR	A
	JP	Z, PARSE_NO_ARG
	LD	A, (HL)
	CP	' '
	JR	NZ, PARSE_COPY_START
	INC	HL
	DEC	B
	JR	PARSE_SKIP_SPACES

PARSE_COPY_START:
	LD	DE, ARG_BUFFER
	LD	C, 0
PARSE_COPY_LOOP:
	LD	A, B
	OR	A
	JR	Z, PARSE_COPY_DONE
	LD	A, (HL)
	CP	' '
	JR	Z, PARSE_COPY_DONE
	LD	A, C
	CP	15
	JP	NC, PARSE_BAD_ARG
	LD	A, (HL)
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	INC	C
	JR	PARSE_COPY_LOOP

PARSE_COPY_DONE:
	XOR	A
	LD	(DE), A

	; Skip trailing spaces.
PARSE_TAIL_SPACES:
	LD	A, B
	OR	A
	JR	Z, PARSE_MAP
	LD	A, (HL)
	CP	' '
	JP	NZ, PARSE_BAD_ARG
	INC	HL
	DEC	B
	JR	PARSE_TAIL_SPACES

PARSE_MAP:
	LD	HL, ARG_BUFFER
	LD	A, (HL)
	OR	A
	JP	Z, PARSE_NO_ARG
	LD	DE, TOK_SHOW
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SHOW
	LD	DE, TOK_VERIFY
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_VERIFY

	LD	DE, TOK_PLAIN
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_PLAIN
	LD	DE, TOK_ZERO
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_PLAIN

	LD	DE, TOK_VT100
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_VT
	LD	DE, TOK_ONE
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_VT

	LD	DE, TOK_ANSI
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_ANSI
	LD	DE, TOK_TWO
	CALL	MATCH_TOKEN
	OR	A
	JP	Z, PARSE_SET_ANSI

PARSE_BAD_ARG:
	LD	A, ERR_BAD_ARG
	RET

PARSE_NO_ARG:
	LD	A, ERR_NO_ARG
	RET

PARSE_SHOW:
	LD	A, ERR_SHOW
	RET

PARSE_SET_PLAIN:
	XOR	A
	LD	(ARG_TERM), A
	XOR	A
	RET

PARSE_SET_VT:
	LD	A, TERM_VT
	LD	(ARG_TERM), A
	XOR	A
	RET

PARSE_SET_ANSI:
	LD	A, TERM_ANSI
	LD	(ARG_TERM), A
	XOR	A
	RET

PARSE_VERIFY:
	LD	A, ERR_VERIFY
	RET

; Compare zero-terminated ARG_BUFFER token (HL) against token at DE.
; Case-insensitive for A-Z.
; Return A=0 match, A=1 no match.
MATCH_TOKEN:
	PUSH	HL
	PUSH	DE
MATCH_LOOP:
	LD	A, (HL)
	CALL	TO_UPPER
	LD	B, A
	LD	A, (DE)
	CALL	TO_UPPER
	CP	B
	JR	NZ, MATCH_NO
	OR	A
	JR	Z, MATCH_YES
	INC	HL
	INC	DE
	JR	MATCH_LOOP

MATCH_NO:
	POP	DE
	POP	HL
	LD	A, 1
	RET

MATCH_YES:
	POP	DE
	POP	HL
	XOR	A
	RET

TO_UPPER:
	CP	'a'
	RET	C
	CP	'z'+1
	RET	NC
	SUB	32
	RET

;===============================================================================
; Console I/O helpers
;===============================================================================

; Get a keystroke from CP/M: A=char (NZ) or A=0 (Z) if none pending.
GETKEY:
	LD	C, 6		; BDOS direct console I/O
	LD	E, $FF	; get character if available
	CALL	BDOS
	OR	A
	RET

FLUSHKEYS:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
FLUSHKEYS1:
	CALL	GETKEY
	JR	Z, FLUSHKEYS2
	JR	FLUSHKEYS1
FLUSHKEYS2:
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET

; Print the byte in A (0-255) as decimal, suppressing leading zeros.
PRTDECB:
	PUSH	BC
	PUSH	DE
	LD	B, 0		; leading-zero suppression flag
	LD	C, 100
	CALL	PRTDECB_DIG
	LD	C, 10
	CALL	PRTDECB_DIG
	ADD	A, '0'
	CALL	PRTCHR
	POP	DE
	POP	BC
	RET

; Divide A by C; print quotient digit unless leading zero; return remainder in A.
PRTDECB_DIG:
	LD	D, 0
PRTDECB_DIG0:
	CP	C
	JR	C, PTDECB_DIG1
	SUB	C
	INC	D
	JR	PRTDECB_DIG0
PTDECB_DIG1:
	LD	E, A		; remainder
	LD	A, D
	OR	A
	JR	NZ, PTDECB_DIG2
	LD	A, B
	OR	A
	JR	Z, PTDECB_DIG3
PTDECB_DIG2:
	LD	B, $FF
	LD	A, D
	ADD	A, '0'
	CALL	PRTCHR
PTDECB_DIG3:
	LD	A, E
	RET

; Print the zero-terminated string addressed by DE.
PRTSTR:
	PUSH	AF
	PUSH	DE

CFG_PRTSTR_LOOP:
	LD	A, (DE)
	OR	A
	JR	Z, CFG_PRTSTR_DONE
	CALL	PRTCHR
	INC	DE
	JR	CFG_PRTSTR_LOOP

CFG_PRTSTR_DONE:
	POP	DE
	POP	AF
	RET

; Print the character in A via CP/M BDOS function 2.
; Preserves AF: CP/M Plus / ZPM3 BDOS fn 2 returns A=0, which broke
; back-to-back PRTCHR calls (e.g. 3-space ruler erase emitted space+NUL+NUL).
PRTCHR:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E, A
	LD	C, $02
	CALL	BDOS
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET

CRLF2:
	CALL	CRLF
CRLF:
	PUSH	AF
	LD	A, 13
	CALL	PRTCHR
	LD	A, 10
	CALL	PRTCHR
	POP	AF
	RET

