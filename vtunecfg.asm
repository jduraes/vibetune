	LD	C, 1
	CALL	TCFG_ANSI_AT
	CALL	TCFG_EL2

	LD	B, TCFG_ORG_ROW - 1
	LD	C, TCFG_ORG_COL
	CALL	TCFG_ANSI_AT
	LD	A, '1'
	CALL	PRTCHR

