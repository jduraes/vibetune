	LD	C, 1
	CALL	TCFG_ANSI_AT
	LD	A, ' '
	CALL	PRTCHR
	CALL	PRTCHR
	CALL	PRTCHR

	LD	A, (CFG_ROWS)
	CP	D
	JR	C, TCFG_DRAW_SCALES_LEFT1
	LD	A, D
	ADD	A, TCFG_ORG_ROW - 1
	LD	B, A
	LD	C, 1
	CALL	TCFG_ANSI_AT
	LD	A, D
	CALL	PRTDECB

TCFG_DRAW_SCALES_LEFT1:
	LD	A, D
	ADD	A, 10
	LD	D, A
	JR	TCFG_DRAW_SCALES_LEFT0

TCFG_DRAW_SCALES_DONE:
