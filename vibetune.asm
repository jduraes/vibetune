	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_RC:
	CALL	SET_CONFIG_RC
	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_COLECO:
	CALL	SET_CONFIG_COLECO
	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_EB:
	CALL	SET_CONFIG_EB_Z180
CHECK_HW_CLI_DONE:
	CALL	CAPTURE_PLATFORM_Z180	; -msx/-rc/etc on Z180 still need slow-I/O
	CALL	SANITIZE_AY_PORTS	; -rc $D8/$D0 collide with Z180 regs @ $C0
	XOR	A
	RET

; If HBIOS is present, record platform id and map Z180_IO_BASE (DCNTL slow-I/O).
; No-op when HBIOS is absent (Z180_IO_BASE stays as set by SET_CONFIG_*).
CAPTURE_PLATFORM_Z180:
	LD	HL, ($FFFC)
	LD	A, 'W'
	CP	(HL)
	RET	NZ
	INC	HL
	LD	A, ~'W'
	CP	(HL)
	RET	NZ
	LD	B, BF_SYSVER
	LD	C, 0
	RST	08			; L := platform id
	LD	A, L
	LD	(HBIOS_PLATFORM_ID), A
	JP	APPLY_Z180_FOR_PLATFORM

; Detect RomWBW HBIOS and query the primary AY device ports.
; Returns A=0 on success, A!=0 on failure.
DETECT_HBIOS_PLATFORM:
	LD	HL, ($FFFC)		; HL := pointer to HBIOS ident
	LD	A, 'W'
	CP	(HL)
	RET	NZ
	INC	HL
	LD	A, ~'W'
	CP	(HL)
	RET	NZ

	LD	B, BF_SYSVER
	LD	C, 0
	RST	08			; L := platform id
	LD	A, L
	LD	(HBIOS_PLATFORM_ID), A

	LD	BC, BC_SYSGET_SNDCNT
	RST	08
	LD	A, E
	OR	A
	RET	Z			; E=0 → no sound devices

	XOR	A
	LD	C, A			; Query sound unit 0
	LD	B, BF_SNDQUERY
	LD	E, BF_SNDQ_DEV
	RST	08
	OR	A
	RET	NZ

	; D=RSEL, E=RDAT from HBIOS query-dev
	LD	A, D
	LD	(PSG_REG_PORT), A
	LD	A, E
	LD	(PSG_DATA_PORT), A
	LD	A, D
	LD	(PSG2_REG_PORT), A
	LD	A, E
	LD	(PSG2_DATA_PORT), A
	CALL	SET_HW_DESC_FROM_RSEL
	LD	A, HW_MODE_AUTO
	LD	(HW_DETECT_MODE), A
	CALL	APPLY_Z180_FOR_PLATFORM
	CALL	SNAPSHOT_PLAY_PSG_PORTS
	XOR	A
	RET

; Map HBIOS platform id to Z180 I/O base (tune.com CFGTBL Z180 column).
APPLY_Z180_FOR_PLATFORM:
	LD	A, (HBIOS_PLATFORM_ID)
	LD	HL, HW_Z180_PLT_TBL
APPLY_Z180_LOOP:
	CP	(HL)
	JR	Z, APPLY_Z180_FOUND
	INC	HL
	LD	A, (HL)
	CP	$FF
	JR	Z, APPLY_Z180_NONE
	INC	HL
	LD	A, (HBIOS_PLATFORM_ID)
	JR	APPLY_Z180_LOOP
APPLY_Z180_NONE:
	LD	A, $FF
	LD	(Z180_IO_BASE), A
	RET
APPLY_Z180_FOUND:
	INC	HL
	LD	A, (HL)
	LD	(Z180_IO_BASE), A
	RET

; Map a known RSEL port to a human-readable hardware description.
; Input: A=RSEL port. Preserves BC/DE/HL.
SET_HW_DESC_FROM_RSEL:
	PUSH	AF
	CP	$A0
	JR	Z, SET_HW_DESC_MSX
	CP	$A1
	JR	Z, SET_HW_DESC_MSX
	CP	$D8
	JR	Z, SET_HW_DESC_RC
	CP	$68
	JR	Z, SET_HW_DESC_Z180
	CP	$51
	JR	Z, SET_HW_DESC_COLECO
	LD	HL, HW_DESC_HBIOS
	JR	SET_HW_DESC_STORE
SET_HW_DESC_MSX:
	LD	HL, HW_DESC_MSX
	JR	SET_HW_DESC_STORE
SET_HW_DESC_RC:
	LD	HL, HW_DESC_EB_RC
	JR	SET_HW_DESC_STORE
SET_HW_DESC_Z180:
	LD	HL, HW_DESC_EB_Z180
	JR	SET_HW_DESC_STORE
SET_HW_DESC_COLECO:
	LD	HL, HW_DESC_COLECO
SET_HW_DESC_STORE:
	LD	(HW_CONFIG_DESC), HL
	POP	AF
	RET

; Probe hardware to determine PSG presence and configuration.
; Tries common port triples and tests each with a Tune-compatible probe.
; Returns A=0 on success (config set), A!=0 on failure.
PROBE_HARDWARE_CONFIG:
	; Z180 EB ($68/$60/$68) before RC/MSX to avoid false positives on SCZ180
	LD	B, $68			; RSEL
	LD	C, $60			; RDAT
	LD	D, $68			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_Z180

	LD	B, $A0			; MSX RSEL
	LD	C, $A1			; RDAT
	LD	D, $A2			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_MSX

	LD	B, $D8			; RC/EB RSEL
	LD	C, $D0			; RDAT
	LD	D, $D8			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_RC

	LD	B, $51			; Coleco RSEL
	LD	C, $50			; RDAT
	LD	D, $52			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_COLECO

	LD	A, 1
	RET

PROBE_HW_SET_MSX:
	CALL	SET_CONFIG_MSX
	JR	PROBE_SUCCESS
PROBE_HW_SET_RC:
	CALL	SET_CONFIG_RC
	JR	PROBE_SUCCESS
PROBE_HW_SET_Z180:
	CALL	SET_CONFIG_EB_Z180
	JR	PROBE_SUCCESS
PROBE_HW_SET_COLECO:
	CALL	SET_CONFIG_COLECO
	JR	PROBE_SUCCESS

PROBE_SUCCESS:
	CALL	APPLY_Z180_FOR_PLATFORM	; probe may pick MSX ports on a Z180 board
	XOR	A
	RET

; Undo probe side effects on port pair BC (RSEL, RDAT): mixer off, amps down.
; Do not write tone period registers (0 = max pitch).
; Input: B=RSEL, C=RDAT.
; Caller (PROBE_AY_PORTS) already holds PSG_IO_SLOW_ENTER — do not nest
; enter/exit here (nested save of DCNTL corrupts the restore on Z180).
PROBE_AY_QUIET:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	LD	A, B
	LD	E, A			; E = RSEL
	LD	A, C
	LD	D, A			; D = RDAT
	LD	B, 0
	LD	C, E
	LD	A, 7
	OUT	(C), A
	LD	C, D
	LD	A, $3F
	OUT	(C), A
	LD	C, E
	LD	A, 8
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	LD	C, E
	LD	A, 9
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	LD	C, E
	LD	A, 10
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	POP	DE
	POP	BC
	POP	AF
	RET

; Tune-compatible AY probe (write $AA to R2, read back via RIN).
; Input: B=RSEL, C=RDAT, D=RIN. Returns A=0 if present, A!=0 if not.
PROBE_AY_PORTS:
	PUSH	BC
	DI
	CALL	PSG_IO_SLOW_ENTER
	PUSH	DE			; preserve RIN (D)
	LD	A, B
	LD	E, A			; E := RSEL
	LD	A, C
	LD	D, A			; D := RDAT
	LD	B, 0
	LD	C, E
	LD	A, 2
	OUT	(C), A
	LD	C, D
	LD	A, $AA
	OUT	(C), A
	LD	C, E
	LD	A, 2
	OUT	(C), A
	POP	DE			; restore RIN in D
	LD	C, D
	IN	A, (C)
	CP	$AA
	LD	A, 1
	JR	NZ, PROBE_AY_DONE
	XOR	A
PROBE_AY_DONE:
	POP	BC
	CALL	PROBE_AY_QUIET
	CALL	PSG_IO_SLOW_EXIT
	EI
	RET

