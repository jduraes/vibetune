; Mute PSG on exit / track switch. Always write mute (do not gate on
; PSG_TOUCHED): a skipped mute leaves the last note sustaining after a crash
; or a reload that never ticked.
START_EXIT_SILENCE:
	XOR	A
	LD	(PSG_TOUCHED), A
	LD	A, (TSFLAG)
	OR	A
	JR	NZ, START_EXIT_SILENCE_CHK
	LD	A, (TS_DUALHW)
	OR	A
	JR	NZ, START_EXIT_SILENCE_CHK
	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	JP	Z, START_EXIT_SILENCE_MODULE
	JP	START_EXIT_SILENCE_ONE
START_EXIT_SILENCE_CHK:
