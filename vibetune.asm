	LD	A, (HBIOS_PLATFORM_ID)
	CP	$08			; SCZ180
	RET	Z
	CP	$0A			; RCZ180
	RET	Z

	LD	A, (TS_PORT1_RSEL)
	CP	$51			; chip1=COLECO?
	JR	Z, TS_FALLBACK_SET_MSX
	LD	A, (TS_PORT1_RSEL)
	CP	$50			; defensive: some variants may report 50h
	JR	Z, TS_FALLBACK_SET_MSX

