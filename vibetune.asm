	OR	A
	JP	NZ, TS_MUTE_BOTH_HARDWARE
	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	JP	Z, START_EXIT_SILENCE_MODULE
START_EXIT_SILENCE_ONE:
	CALL	RESTORE_PLAY_PSG_PORTS
	JP	PSG_MUTE_DIRECT
START_EXIT_SILENCE_MODULE:
	JP	TSMOD_MUTE

; Milestone 1A: Load display + AY config from VTUNE.CFG if present.
; Config file format (binary; written by vtunecfg.com):
;   byte 0: magic = 0xA5
;   byte 1: DISP_MODE (0=plain, 1=VT100, 2=ANSI)
;   byte 2: flags (bit 0 = ANSI colour)
;   byte 3: rows (0 -> default 24)
;   byte 4: cols (0 -> default 80)
;   byte 5: TS topology (0=auto, 1=dual-card, 2=module;
;           absent in old files -> auto)
;   byte 6: primary AY card (0=auto, 1=MSX, 2=RC, 3=EB, 4=Coleco)
;   byte 7: second AY card for dual-card (0=none, 1..4)
; Missing file or invalid magic → DISP_MODE stays DISP_PLAIN, cards auto.
; CLI (-msx/-rc/-eb/-coleco/-tsm) overrides CFG. No VT100/ANSI probing.
; Output: DISP_MODE is valid and stable for all subsequent display calls.
#DEFINE CFG_MAGIC $A5
DETECT_DISPLAY_MODE:
	; Build FCB for VTUNE.CFG in CFG_FCB
	CALL	BUILD_CFG_FCB
	; Set DMA to DMA_BUFFER (safe: structural validation not yet run)
	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS
	; Open config file (BDOS 0Fh)
	LD	DE, CFG_FCB
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, DETECT_DISP_NO_CFG	; file not found — use default
	; Read one 128-byte block (BDOS 14h)
	XOR	A
	LD	(DMA_BUFFER+5), A	; old 5-byte CFG files -> byte 5 reads as 0 (TS auto)
	LD	DE, CFG_FCB
	LD	C, $14
	CALL	BDOS
	OR	A
	JR	NZ, DETECT_DISP_CLOSE	; read error — use default
	; Validate magic byte
	LD	A, (DMA_BUFFER)
	CP	CFG_MAGIC
	JR	NZ, DETECT_DISP_CLOSE
	; Load DISP_MODE from byte 1
	LD	A, (DMA_BUFFER+1)
	CP	DISP_ANSI + 1
	JR	NC, DETECT_DISP_CLOSE	; out of range — use default
	LD	(DISP_MODE), A
	; Byte 2: flags (bit 0 = ANSI colour)
	LD	A, (DMA_BUFFER+2)
	AND	$01
	LD	(CFG_FLAGS), A
	; Byte 3: rows (0 -> default 24)
	LD	A, (DMA_BUFFER+3)
	OR	A
	JR	NZ, DETECT_DISP_ROWS_OK
	LD	A, 24
DETECT_DISP_ROWS_OK:
	LD	(CFG_ROWS), A
	; Byte 4: cols (0 -> default 80)
	LD	A, (DMA_BUFFER+4)
	OR	A
	JR	NZ, DETECT_DISP_COLS_OK
	LD	A, 80
DETECT_DISP_COLS_OK:
	LD	(CFG_COLS), A
	; Byte 5: TS topology. CLI (-tsm) wins: do not clobber a non-auto value.
	LD	A, (TS_TOPOLOGY)
	OR	A
	JR	NZ, DETECT_DISP_CARDS
	LD	A, (DMA_BUFFER+5)
	CP	3
	JR	NC, DETECT_DISP_CARDS	; out of range — keep auto
	LD	(TS_TOPOLOGY), A
DETECT_DISP_CARDS:
	; Bytes 6-7: AY cards (old files zero-filled → auto / none)
	LD	A, (DMA_BUFFER+6)
	CP	5
	JR	C, DETECT_DISP_C1_OK
	XOR	A
DETECT_DISP_C1_OK:
	LD	(CFG_AY_CARD1), A
	LD	A, (DMA_BUFFER+7)
	CP	5
	JR	C, DETECT_DISP_C2_OK
	XOR	A
DETECT_DISP_C2_OK:
	LD	(CFG_AY_CARD2), A
DETECT_DISP_CLOSE:
	; Close config file (BDOS 10h)
	LD	DE, CFG_FCB
	LD	C, $10
	CALL	BDOS
DETECT_DISP_NO_CFG:
	; Final range clamp (ensures DISP_MODE is always valid)
	LD	A, (DISP_MODE)
	CP	DISP_ANSI + 1
	JR	C, DETECT_DISP_DONE
	XOR	A
	LD	(DISP_MODE), A
DETECT_DISP_DONE:
	RET

; From CP/M page 0: high byte of BDOS vector at 7; module load stops one page below.
HEAPENDB_INIT:
	LD	A, (7)
	DEC	A
	LD	(HEAPENDB), A
	RET

; Zero player + TS context before load (VARS .. MUSIC_BUF-1).
; Starts at VARS, NOT HEAP: parse buffers / TRACK_LIST / BULBA_PORTS sit
; below VARS and must survive. Must NOT clear through HEAPEND ($C000): that
; range includes the CP/M stack, so an LDIR there on track reload corrupts
; return addresses (crash + sustained last note). MUSIC_BUF is overwritten
; by LOAD_MUSIC_FILE.
HEAP_CLEAR:
	LD	HL, VARS
	XOR	A
	LD	(HL), A
	LD	DE, VARS + 1
	LD	BC, MUSIC_BUF - VARS - 1
	LDIR
	RET

; Build a CP/M FCB in CFG_FCB for VTUNE.CFG (drive 0, current drive).
BUILD_CFG_FCB:
	LD	HL, CFG_FCB
	LD	B, 36
BUILD_CFG_CLR:
	XOR	A
	LD	(HL), A
	INC	HL
	DJNZ	BUILD_CFG_CLR
	; Name field: "VTUNE   CFG" (8+3, space-padded)
	LD	HL, CFG_FCB + 1
	LD	DE, MSG_CFG_NAME
	LD	B, 11
BUILD_CFG_NAME:
	LD	A, (DE)
	LD	(HL), A
	INC	HL
	INC	DE
	DJNZ	BUILD_CFG_NAME
	RET

; Parse one command-line file argument and classify extension.
; If no extension is present, probe supported extensions in this order:
;   .pt3, .pt2, .mym
; Returns A = ERR_OK, ERR_NO_ARG, ERR_TOO_MANY_ARGS,
;            ERR_UNSUPPORTED_FORMAT, ERR_INVALID_FILENAME, ERR_FILE_NOT_FOUND.
PARSE_AND_CLASSIFY:
	CALL	PARSE_CMDLINE
	OR	A
	RET	NZ
	LD	A, (RUN_MODE)
	CP	RUNMODE_PLAY
	JR	Z, PARSE_CLASSIFY_FILE
	XOR	A
	RET

PARSE_CLASSIFY_FILE:
	JP	CLASSIFY_ARG_EXTENSION

; Case-insensitive substring search within bounded haystack (B bytes at HL).
STRINDEX_UP_LEN:
STRINDEX_UP_LEN_TRY:
	LD	A, B
	OR	A
	JR	Z, STRINDEX_UP_LEN_FAIL
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_UP
	POP	DE
	POP	HL
	JR	Z, STRINDEX_UP_LEN_OK
	INC	HL
	DEC	B
	JR	STRINDEX_UP_LEN_TRY
STRINDEX_UP_LEN_FAIL:
	OR	$FF
	RET
STRINDEX_UP_LEN_OK:
	XOR	A
	RET

; Substring search in default FCB name+ext ($5D..$67, 11 bytes). Leading switches
; only (e.g. vtune -delay rl2wof). Interior NUL bytes are skipped, not fatal.
STRINDEX_FCB:
STRINDEX_FCB_TRY:
	LD	A, B
	OR	A
	JR	Z, STRINDEX_FCB_FAIL
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_UP
	POP	DE
	POP	HL
	JR	Z, STRINDEX_FCB_OK
	INC	HL
	DEC	B
	JR	STRINDEX_FCB_TRY
STRINDEX_FCB_FAIL:
	OR	$FF
	RET
STRINDEX_FCB_OK:
	XOR	A
	RET

; Z = found if needle appears in bounded CLI tail or default FCB name field.
; DE = needle on entry. Uses GET_CMD_TAIL_LEN (does not require HL=$81).
SCAN_SWITCH_IN_CMD:
	PUSH	DE
	CALL	GET_CMD_TAIL_LEN
	POP	DE
	LD	A, B
	OR	A
	JR	Z, SCAN_SWITCH_FCB
	CALL	STRINDEX_UP_LEN
	RET	Z
SCAN_SWITCH_FCB:
	LD	HL, FCB + 1
	LD	B, 11
	JP	STRINDEX_FCB

; Scan command line for switches (any token order). Primary: $0081 like tune.com.
SCAN_CMDLINE_SWITCHES:
	LD	DE, MSG_SWITCH_LIST
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_LIST
	LD	A, RUNMODE_LIST
	LD	(RUN_MODE), A
SCAN_SW_NO_LIST:
	LD	DE, MSG_SWITCH_HELP
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_HELP
	LD	A, RUNMODE_HELP
	LD	(RUN_MODE), A
SCAN_SW_NO_HELP:
	LD	DE, MSG_SWITCH_CREDITS
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_CREDITS
	LD	A, RUNMODE_CREDITS
	LD	(RUN_MODE), A
SCAN_SW_NO_CREDITS:
	LD	DE, MSG_SWITCH_LOOP
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_LOOP
	LD	A, 1
	LD	(LOOP_REQ), A		; applied once run mode is known
SCAN_SW_NO_LOOP:
	LD	DE, MSG_SWITCH_MSX
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_MSX
	LD	A, HW_MODE_MSX
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_MSX:
	LD	DE, MSG_SWITCH_RC
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_RC
	LD	A, HW_MODE_RC
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_RC:
	LD	DE, MSG_SWITCH_COLECO
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_COLECO
	LD	A, HW_MODE_COLECO
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_COLECO:
	LD	DE, MSG_SWITCH_EB
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_EB
	LD	A, HW_MODE_EB
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_EB:
	LD	DE, MSG_SWITCH_DELAY
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_DELAY
	LD	A, 1
	LD	(DELAYMD), A
SCAN_SW_NO_DELAY:
	LD	DE, MSG_SWITCH_TSM
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_DONE
	LD	A, TS_TOPO_MODULE
	LD	(TS_TOPOLOGY), A
SCAN_SW_DONE:
	RET

; Z = 1 if A is NUL, CR, or CP/M end-of-line (high bit set on last byte).
CMD_CHAR_END:
	AND	$7F
	OR	A
	RET	Z
	CP	0DH
	RET

; Compare strings at HL and DE (case-insensitive). HL may end at NUL, CR, or
; CP/M high-bit delimiter. Needle (DE) drives the walk; Z = needle consumed.
; HL is preserved in all cases (callers compare the same token against
; several needles in a row). No PUSH/POP AF around the compare — POP AF
; would restore F and discard the CP result.
STRCMP_UP:
	PUSH	HL
STRCMP_UP_LOOP:
	LD	A, (DE)
	OR	A
	JR	Z, STRCMP_UP_MATCH
	PUSH	AF
	CALL	TO_UPPER
	LD	C, A
	POP	AF
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, STRCMP_UP_NOMATCH
	CALL	TO_UPPER
	CP	C
	JR	NZ, STRCMP_UP_NOMATCH
	INC	HL
	INC	DE
	JR	STRCMP_UP_LOOP
STRCMP_UP_NOMATCH:
	POP	HL
	OR	$FF
	RET
STRCMP_UP_MATCH:
	POP	HL
	XOR	A
	RET

; Parse CP/M command line: tune.com-style tail scan + default FCB filename.
; Returns A = error code.
PARSE_CMDLINE:
	XOR	A
	LD	(HW_DETECT_MODE), A
	LD	(ARG_HAVE), A
	LD	HL, ARG_BUFFER
	LD	B, 128

PARSE_CLR_ARG_BUF:
	LD	(HL), A
	INC	HL
	DJNZ	PARSE_CLR_ARG_BUF
	CALL	SCAN_CMDLINE_SWITCHES
	; Reject unknown -foo tokens even in -list/-help/-credits (those modes
	; used to skip the token walk, so typos like -tms were silently ignored).
	CALL	VALIDATE_SWITCH_TOKENS
	OR	A
	RET	NZ
	LD	A, (RUN_MODE)
	CP	RUNMODE_LIST
	JR	Z, PARSE_CL_DONE
	CP	RUNMODE_HELP
	JR	Z, PARSE_CL_DONE
	CP	RUNMODE_CREDITS
	JR	Z, PARSE_CL_DONE
	CALL	COPY_FCB_TO_ARG
	LD	A, (ARG_HAVE)
	LD	(PARSE_SWITCH_ONLY), A
	CALL	PARSE_TOKENS_FOR_FILENAME
	OR	A
	RET	NZ
	LD	A, (RUN_MODE)
	CP	RUNMODE_LIST
	JR	Z, PARSE_CL_DONE
	CP	RUNMODE_HELP
	JR	Z, PARSE_CL_DONE
	CP	RUNMODE_CREDITS
	JR	Z, PARSE_CL_DONE
	LD	A, (ARG_HAVE)
	OR	A
	JP	Z, PARSE_ERR_NO_ARG
PARSE_CL_DONE:
	XOR	A
	RET

; Copy CP/M default FCB ($5C) filename into ARG_BUFFER when usable.
; Blank or '-' first name char => leave ARG_HAVE=0 (caller uses token scan).
COPY_FCB_TO_ARG:
	XOR	A
	LD	(ARG_HAVE), A
	LD	HL, FCB+1
	LD	A, (HL)
	CP	' '
	RET	Z
	CP	'-'
	RET	Z
	LD	DE, ARG_BUFFER
	LD	B, 8

COPY_FCB_NAME:
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_NAME_SKIP
	CALL	TO_UPPER
	LD	(DE), A
	INC	DE
	INC	HL
	DJNZ	COPY_FCB_NAME
	JR	COPY_FCB_EXT

COPY_FCB_NAME_SKIP:
	INC	HL
	DJNZ	COPY_FCB_NAME

COPY_FCB_EXT:
	LD	HL, FCB+9
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_DONE
	LD	A, '.'
	LD	(DE), A
	INC	DE
	LD	B, 3

COPY_FCB_EXT_LOOP:
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_DONE
	CALL	TO_UPPER
	LD	(DE), A
	INC	DE
	INC	HL
	DJNZ	COPY_FCB_EXT_LOOP

COPY_FCB_DONE:
	XOR	A
	LD	(DE), A
	LD	A, 1
	LD	(ARG_HAVE), A
	RET

; Effective command-tail length from CP/M byte $0080, clamped to first
; NUL/CR/high-bit terminator inside that declared span.
; ZPM3 quirk: $0080 may be 0 even when a tail is present at $0081 — in that
; case derive the length by scanning to the first terminator (max 127).
; Returns B = effective length, HL = $0081.
GET_CMD_TAIL_LEN:
	LD	A, ($0080)
	OR	A
	JR	NZ, GET_CMD_TAIL_DECLARED
	LD	HL, $0081
	LD	B, 0
GET_CMD_TAIL_SCAN:
	LD	A, B
	CP	127
	JR	Z, GET_CMD_TAIL_DONE
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, GET_CMD_TAIL_DONE
	INC	HL
	INC	B
	JR	GET_CMD_TAIL_SCAN
GET_CMD_TAIL_DECLARED:
	LD	D, A
	LD	HL, $0081
	LD	B, 0
GET_CMD_TAIL_CLAMP:
	LD	A, D
	OR	A
	JR	Z, GET_CMD_TAIL_DONE
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, GET_CMD_TAIL_DONE
	INC	HL
	INC	B
	DEC	D
	JR	GET_CMD_TAIL_CLAMP

GET_CMD_TAIL_DONE:
	LD	HL, $0081
	RET

; Walk command tail when FCB is blank or switch-first; take first non-switch token.
; Returns A = ERR_TOO_MANY_ARGS or ERR_OK (0).
PARSE_TOKENS_FOR_FILENAME:
	CALL	GET_CMD_TAIL_LEN

PARSE_TOK_SKIP:
	LD	A, B
	OR	A
	RET	Z
	LD	A, (HL)
	CP	' '
	JR	Z, PARSE_TOK_ADV
	CALL	CMD_CHAR_END
	JR	Z, PARSE_TOK_ADV
	JR	PARSE_TOK_TOKEN

PARSE_TOK_ADV:
	INC	HL
	DEC	B
	JR	PARSE_TOK_SKIP

PARSE_TOK_TOKEN:
	LD	DE, ARG_SCRATCH
	LD	A, (HL)
	CP	'"'
	JR	Z, PARSE_TOK_QUOTED

PARSE_TOK_UNQ:
	LD	A, B
	OR	A
	JR	Z, PARSE_TOK_DISPATCH
	LD	A, (HL)
	CP	' '
	JR	Z, PARSE_TOK_DISPATCH
	CALL	CMD_CHAR_END
	JR	Z, PARSE_TOK_DISPATCH
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	JR	PARSE_TOK_UNQ

PARSE_TOK_QUOTED:
	INC	HL
	DEC	B

PARSE_TOK_QLOOP:
	LD	A, B
	OR	A
	JR	Z, PARSE_TOK_DISPATCH
	LD	A, (HL)
	CP	'"'
	JR	Z, PARSE_TOK_QEND
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	JR	PARSE_TOK_QLOOP

PARSE_TOK_QEND:
	INC	HL
	DEC	B

PARSE_TOK_DISPATCH:
	XOR	A
	LD	(DE), A
	PUSH	HL			; keep tail position across switch matching
	LD	HL, ARG_SCRATCH
	CALL	APPLY_IF_SWITCH
	POP	HL
	CP	2
	JP	Z, PARSE_ERR_BAD_SWITCH
	OR	A
	JR	NZ, PARSE_TOK_SKIP_AFTER
	LD	A, (PARSE_SWITCH_ONLY)
	OR	A
	JR	NZ, PARSE_TOK_SKIP_AFTER
	LD	A, (ARG_HAVE)
	OR	A
	JP	NZ, PARSE_ERR_TOO_MANY

PARSE_TOK_TAKE_FILENAME:
	LD	A, 1
	LD	(ARG_HAVE), A
	LD	HL, ARG_SCRATCH
	LD	DE, ARG_BUFFER

PARSE_TOK_COPY:
	LD	A, (HL)
	LD	(DE), A
	OR	A
	RET	Z
	INC	HL
	INC	DE
	JR	PARSE_TOK_COPY

PARSE_TOK_SKIP_AFTER:
	JP	PARSE_TOK_SKIP

; HL = token. Returns A=0 filename, A=1 known switch, A=2 unknown switch.
APPLY_IF_SWITCH:
	LD	A, (HL)
	CP	'-'
	JR	Z, APPLY_IF_SWITCH_CHK
	XOR	A
	RET
APPLY_IF_SWITCH_CHK:
	CALL	IS_KNOWN_SWITCH_TOKEN
	OR	A
	JR	Z, APPLY_IF_SWITCH_Y
	LD	A, 2
	RET
APPLY_IF_SWITCH_Y:
	LD	A, 1
	RET

; HL = NUL-terminated token. Z (A=0) if it exactly matches a known switch.
IS_KNOWN_SWITCH_TOKEN:
	LD	DE, MSG_SWITCH_LIST
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_HELP
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_CREDITS
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_LOOP
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_MSX
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_RC
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_COLECO
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_EB
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_DELAY
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	LD	DE, MSG_SWITCH_TSM
	CALL	SWITCH_TOKEN_EQ
	RET	Z
	OR	$FF
	RET

; Exact case-insensitive match of token HL to needle DE (both must end together).
; Z if equal. Preserves HL. Clobbers AF/BC/DE.
SWITCH_TOKEN_EQ:
	PUSH	HL
	PUSH	DE
SWITCH_TOKEN_EQ_LOOP:
	LD	A, (DE)
	OR	A
	JR	Z, SWITCH_TOKEN_EQ_NEEDLE_END
	PUSH	AF
	CALL	TO_UPPER
	LD	C, A
	POP	AF
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, SWITCH_TOKEN_EQ_NO
	CALL	TO_UPPER
	CP	C
	JR	NZ, SWITCH_TOKEN_EQ_NO
	INC	HL
	INC	DE
	JR	SWITCH_TOKEN_EQ_LOOP
SWITCH_TOKEN_EQ_NEEDLE_END:
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	NZ, SWITCH_TOKEN_EQ_NO
	POP	DE
	POP	HL
	XOR	A
	RET
SWITCH_TOKEN_EQ_NO:
	POP	DE
	POP	HL
	OR	$FF
	RET

; Walk command-tail tokens; any -foo that is not a known switch → error.
; Same tokenizer bounds as PARSE_TOKENS_FOR_FILENAME. Returns A=0 or ERR_*.
VALIDATE_SWITCH_TOKENS:
	CALL	GET_CMD_TAIL_LEN
VAL_SW_SKIP:
	LD	A, B
	OR	A
	JR	Z, VAL_SW_OK
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, VAL_SW_OK
	CP	' '
	JR	Z, VAL_SW_ADV
	CP	9
	JR	Z, VAL_SW_ADV
	JR	VAL_SW_TOKEN
VAL_SW_ADV:
	INC	HL
	DEC	B
	JR	VAL_SW_SKIP
VAL_SW_TOKEN:
	LD	DE, ARG_SCRATCH
VAL_SW_UNQ:
	LD	A, B
	OR	A
	JR	Z, VAL_SW_DISPATCH
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, VAL_SW_DISPATCH
	CP	' '
	JR	Z, VAL_SW_DISPATCH
	CP	9
	JR	Z, VAL_SW_DISPATCH
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	JR	VAL_SW_UNQ
VAL_SW_DISPATCH:
	XOR	A
	LD	(DE), A
	PUSH	HL
	PUSH	BC
	LD	HL, ARG_SCRATCH
	LD	A, (HL)
	CP	'-'
	JR	NZ, VAL_SW_NEXT
	CALL	IS_KNOWN_SWITCH_TOKEN
	OR	A
	JR	Z, VAL_SW_NEXT
	POP	BC
	POP	HL
	LD	A, ERR_UNKNOWN_SWITCH
	RET
VAL_SW_NEXT:
	POP	BC
	POP	HL
	JR	VAL_SW_SKIP
VAL_SW_OK:
	XOR	A
	RET

PARSE_ERR_NO_ARG:
	LD	A, ERR_NO_ARG
	RET

PARSE_ERR_TOO_MANY:
	LD	A, ERR_TOO_MANY_ARGS
	RET

PARSE_ERR_BAD_SWITCH:
	LD	A, ERR_UNKNOWN_SWITCH
	RET

; Classify ARG_BUFFER extension as PTx or MYM.
; Returns A = ERR_OK or ERR_UNSUPPORTED_FORMAT.
CLASSIFY_ARG_EXTENSION:
	LD	HL, ARG_BUFFER
	LD	DE, 0

CLASS_SCAN_LOOP:
	LD	A, (HL)
	OR	A
	JR	Z, CLASS_SCAN_DONE
	CP	'.'
	JR	NZ, CLASS_SCAN_NEXT
	LD	D, H
	LD	E, L

CLASS_SCAN_NEXT:
	INC	HL
	JR	CLASS_SCAN_LOOP

CLASS_SCAN_DONE:
	LD	A, D
	OR	E
	JR	Z, CLASS_RESOLVE_MISSING_EXT
	EX	DE, HL
	INC	HL

	LD	A, (HL)
	OR	A
	JR	Z, CLASS_UNSUPPORTED
	CALL	TO_UPPER
	CP	'P'
	JR	Z, CLASS_TRY_PTX
	CP	'M'
	JR	Z, CLASS_TRY_MYM
	JR	CLASS_UNSUPPORTED

CLASS_TRY_PTX:
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'T'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	CP	'2'
	JR	Z, CLASS_PTX_END
	CP	'3'
	JR	NZ, CLASS_UNSUPPORTED

CLASS_PTX_END:
	INC	HL
	LD	A, (HL)
	OR	A
	JR	NZ, CLASS_UNSUPPORTED
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	XOR	A
	RET

CLASS_TRY_MYM:
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'Y'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'M'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	OR	A
	JR	NZ, CLASS_UNSUPPORTED
	LD	A, ENGINE_MYM
	LD	(FILE_ENGINE), A
	XOR	A
	RET

CLASS_UNSUPPORTED:
	LD	A, ERR_UNSUPPORTED_FORMAT
	RET

CLASS_RESOLVE_MISSING_EXT:
	JP	RESOLVE_MISSING_EXTENSION

; Resolve extensionless ARG_BUFFER by probing files in this order:
;   .PT3 -> .PT2 -> .MYM
; On success, ARG_BUFFER is updated in-place with the found extension and
; FILE_ENGINE is set accordingly.
; Returns A = ERR_OK, ERR_INVALID_FILENAME, or ERR_FILE_NOT_FOUND.
RESOLVE_MISSING_EXTENSION:
	; Find NUL terminator in ARG_BUFFER (HL points at end).
	LD	HL, ARG_BUFFER
RESOLVE_FIND_END:
	LD	DE, ARG_BUFFER + 127
	LD	A, H
	CP	D
	JR	C, RESOLVE_FIND_STEP
	JR	NZ, RESOLVE_HAVE_END
	LD	A, L
	CP	E
	JR	NC, RESOLVE_HAVE_END

RESOLVE_FIND_STEP:
	LD	A, (HL)
	OR	A
	JR	Z, RESOLVE_HAVE_END
	CP	0DH
	JR	Z, RESOLVE_HAVE_END
	INC	HL
	JR	RESOLVE_FIND_END

RESOLVE_HAVE_END:
	PUSH	HL			; keep end pointer for each candidate and final restore

	; Try .PT3 first
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_PT3
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_TRY_PT2
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_TRY_PT2:
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_PT2
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_TRY_MYM
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_TRY_MYM:
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_MYM
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_FAIL_NOT_FOUND
	LD	A, ENGINE_MYM
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_FAIL_INVALID:
	POP	HL
	LD	(HL), 0			; restore original extensionless ARG_BUFFER
	LD	A, ERR_INVALID_FILENAME
	RET

RESOLVE_FAIL_NOT_FOUND:
	POP	HL
	LD	(HL), 0			; restore original extensionless ARG_BUFFER
	LD	A, ERR_FILE_NOT_FOUND
	RET

; Append ".PT3" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_PT3:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'P'
	INC	HL
	LD	(HL), 'T'
	INC	HL
	LD	(HL), '3'
	INC	HL
	LD	(HL), 0
	RET

; Append ".PT2" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_PT2:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'P'
	INC	HL
	LD	(HL), 'T'
	INC	HL
	LD	(HL), '2'
	INC	HL
	LD	(HL), 0
	RET

; Append ".MYM" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_MYM:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'M'
	INC	HL
	LD	(HL), 'Y'
	INC	HL
	LD	(HL), 'M'
	INC	HL
	LD	(HL), 0
	RET

; Probe FCB_WORK existence by open/close.
; Returns A=1 if file exists, A=0 if missing.
PROBE_FCB_EXISTS:
	LD	DE, FCB_WORK
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, PROBE_FCB_MISS
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	LD	A, 1
	RET

PROBE_FCB_MISS:
	XOR	A
	RET

; Stage 2 validation: build CP/M FCB from argument and verify open/read path.
; Returns A = ERR_OK, ERR_INVALID_FILENAME, ERR_FILE_NOT_FOUND, ERR_FILE_READ.
VALIDATE_FILE_ACCESS:
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	RET	NZ

	LD	DE, FCB_WORK
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, VALIDATE_FILE_MISSING

	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS

	LD	DE, FCB_WORK
	LD	C, $14
	CALL	BDOS
	CP	0
	JR	Z, VALIDATE_FILE_CLOSE_OK
	CP	1
	JR	Z, VALIDATE_FILE_CLOSE_OK

	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	LD	A, ERR_FILE_READ
	RET

VALIDATE_FILE_CLOSE_OK:
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	XOR	A
	RET

VALIDATE_FILE_MISSING:
	LD	A, ERR_FILE_NOT_FOUND
	RET

; Stage 2 lightweight structural checks from first DMA block.
; Returns A = ERR_OK or ERR_INVALID_DATA.
VALIDATE_FORMAT_STRUCTURE:
	LD	A, (FILE_ENGINE)
	CP	ENGINE_MYM
	JR	Z, VALIDATE_MYM_STRUCTURE
	CP	ENGINE_PTX
	JR	Z, VALIDATE_PTX_STRUCTURE
	LD	A, ERR_INVALID_DATA
	RET

VALIDATE_MYM_STRUCTURE:
	; First word = frame/row count; reject zero or absurdly large.
	LD	A, (DMA_BUFFER)
	LD	HL, DMA_BUFFER+1
	OR	(HL)
	JP	Z, VALIDATE_FORMAT_INVALID
	LD	A, (DMA_BUFFER+1)
	CP	64
	JP	NC, VALIDATE_FORMAT_INVALID
	XOR	A
	RET

VALIDATE_PTX_STRUCTURE:
	CALL	PTX_PRINTABLE_PREFIX
	OR	A
	JP	NZ, VALIDATE_FORMAT_INVALID
	CALL	PTX_MATCH_VORTEX_HEADER
	OR	A
	JR	Z, VALIDATE_PTX_OK
	CALL	PTX_MATCH_PROTRACKER_HEADER
	OR	A
	JP	NZ, VALIDATE_FORMAT_INVALID

VALIDATE_PTX_OK:
	XOR	A
	RET

PTX_PRINTABLE_PREFIX:
	LD	HL, DMA_BUFFER
	LD	B, 16

PTX_PRINTABLE_LOOP:
	LD	A, (HL)
	CALL	IS_PRINTABLE_ASCII
	JR	NZ, PTX_PRINTABLE_BAD
	INC	HL
	DJNZ	PTX_PRINTABLE_LOOP
	XOR	A
	RET

PTX_PRINTABLE_BAD:
	LD	A, 1
	RET

PTX_MATCH_VORTEX_HEADER:
	LD	HL, DMA_BUFFER
	JR	PTX_MATCH_VORTEX_HL

PTX_MATCH_VORTEX_MUSIC:
	LD	HL, MUSIC_BUF

PTX_MATCH_VORTEX_HL:
	LD	A, (HL)
	CP	'V'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'o'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	't'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'e'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'x'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	' '
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'T'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'a'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'c'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
