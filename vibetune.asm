; Write AY register REG with value VAL.
; Inputs: B = register number (0-13), C = value.
; Clobbers: AF.
PSG_WRITE_REG:
	PUSH	BC
	CALL	PSG_IO_SLOW_ENTER
	LD	A, C			; Save value
	LD	(PSG_TEMP_VAL), A
	LD	A, (PSG_REG_PORT)	; Load RSEL port
	LD	C, A
	LD	A, B			; Register number
	LD	B, 0
	OUT	(C), A			; Write register select
	LD	A, (PSG_DATA_PORT)	; Load RDAT port
	LD	C, A
	LD	A, (PSG_TEMP_VAL)	; Recover value
	OUT	(C), A			; Write data
	CALL	PSG_IO_SLOW_EXIT
	POP	BC
	RET



; Write AY register REG with value VAL to optional chip B.
; Inputs: B = register number (0-13), C = value.
; Clobbers: AF, D, E.
PSG_WRITE_REG_B:
	PUSH	BC
	CALL	PSG_IO_SLOW_ENTER
	LD	A, C			; Save value
	LD	(PSG_TEMP_VAL), A
	LD	A, (PSG2_REG_PORT)	; Load RSEL port for chip B
	LD	C, A
	LD	A, B			; Register number
	LD	B, 0
	OUT	(C), A			; Write register select
	LD	A, (PSG2_DATA_PORT)	; Load RDAT port for chip B
	LD	C, A
	LD	A, (PSG_TEMP_VAL)	; Recover value
	OUT	(C), A			; Write data
	CALL	PSG_IO_SLOW_EXIT
	POP	BC
	RET

; Milestone 8 prep: route register writes through output mode.
; AUDIO_OUT_AY: write only chip A.
; AUDIO_OUT_TURBOSOUND: mirror writes to both chips.
PSG_WRITE_ROUTED:
	LD	A, 1
	LD	(PSG_TOUCHED), A
	LD	A, (AUDIO_OUT_MODE)
	CP	AUDIO_OUT_TURBOSOUND
	JR	NZ, PSG_WRITE_ROUTED_A
	CALL	PSG_WRITE_REG
	JP	PSG_WRITE_REG_B
PSG_WRITE_ROUTED_A:
	JP	PSG_WRITE_REG

; Z180 slow I/O (tune.com SLOWIO/NORMIO). Z180_IO_BASE=$C0 on RCZ180 EB per CFGTBL.
PSG_IO_SLOW_ENTER:
	PUSH	AF
	PUSH	BC
	LD	A, (Z180_IO_BASE)
	CP	$FF
	JR	Z, PSG_IO_ENTER_DONE
	ADD	A, $32
	LD	C, A
	LD	B, 0
	IN	A, (C)
	LD	(PSG_IO_DCSAV), A
	OR	$30
	OUT	(C), A
PSG_IO_ENTER_DONE:
	POP	BC
	POP	AF
	RET

PSG_IO_SLOW_EXIT:
	PUSH	AF
	PUSH	BC
	LD	A, (Z180_IO_BASE)
	CP	$FF
	JR	Z, PSG_IO_EXIT_DONE
	ADD	A, $32
	LD	C, A
	LD	B, 0
	LD	A, (PSG_IO_DCSAV)
	OUT	(C), A
PSG_IO_EXIT_DONE:
	POP	BC
	POP	AF
	RET

; Bulk-write 14 AY registers from (HL). Matches tune.com ROUT/LOUT for RomWBW.
; Input: HL = register block (regs 0-13).
PSG_ROUT_BLOCK:
	LD	A, 1
	LD	(PSG_TOUCHED), A
	DI
	CALL	PSG_IO_SLOW_ENTER
	LD	A, (PSG_DATA_PORT)
	LD	D, A
	LD	A, (PSG_REG_PORT)
	LD	E, A
	LD	B, 13
	XOR	A
	LD	C, E
PSG_ROUT_LOOP:
	OUT	(C), A
	LD	C, D
	OUTI
	LD	C, E
	INC	A
	CP	13
	JR	NZ, PSG_ROUT_LOOP
	OUT	(C), A
	LD	A, (HL)
	AND	A
	JP	M, PSG_ROUT_DONE
	LD	C, D
	OUT	(C), A
PSG_ROUT_DONE:
	CALL	PSG_IO_SLOW_EXIT
	EI
	RET

; Mute like tune.com MUTE+ROUT: zero shadow block, flush to hardware.
PSG_MUTE_ROUT:
	LD	HL, PSG_MUTE_REGS
	LD	B, 14
	XOR	A
PSG_MUTE_ZERO:
	LD	(HL), A
	INC	HL
	DJNZ	PSG_MUTE_ZERO
	LD	HL, PSG_MUTE_REGS
	JP	PSG_ROUT_BLOCK

PSG_MUTE_ALL:
	LD	A, 1
	LD	(PSG_TOUCHED), A
	; tune.com default: direct ROUT mute (zeros + bulk write), not BF_SNDRESET.
	JP	PSG_MUTE_ROUT

PSG_SILENCE:
	JP	PSG_MUTE_ALL

; Pause: zero amplitude regs (8-10) + mixer (7=$3F) to ensure 100% note mute.
PSG_MIXER_OFF:
	; Zero amplitude channel A (reg 8)
	LD	B, 8
	LD	C, 0
	CALL	PSG_WRITE_ROUTED
	; Zero amplitude channel B (reg 9)
	LD	B, 9
	LD	C, 0
	CALL	PSG_WRITE_ROUTED
	; Zero amplitude channel C (reg 10)
	LD	B, 10
	LD	C, 0
	CALL	PSG_WRITE_ROUTED
	; Mute mixer output (reg 7 = $3F)
	LD	B, 7
	LD	C, $3F
	JP	PSG_WRITE_ROUTED

PSG_MUTE_DIRECT:
	JP	PSG_MUTE_ALL

; Playback state machine dispatcher.
; Called once per audio frame (50 Hz, polled in M6 main loop).
; Checks PLAY_STATE; if PLAYING dispatches to per-engine tick.
; Returns: nothing. All registers preserved.
PLAYBACK_TICK:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	A, (PLAY_STATE)
	CP	PLAY_PLAYING
	JR	NZ, PLAYBACK_TICK_DONE
	; Dispatch on FILE_ENGINE
	LD	A, (FILE_ENGINE)
	CP	ENGINE_PTX
	JP	Z, PTX_ENGINE_TICK
	CP	ENGINE_MYM
	JP	Z, MYM_ENGINE_TICK
PLAYBACK_TICK_DONE:
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET

