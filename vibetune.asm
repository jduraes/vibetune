	LD	(PSG_REG_PORT), A
	LD	A, (TS_PORT2_RDAT)
	LD	(PSG_DATA_PORT), A
	CALL	PSG_MUTE_ROUT
	JP	RESTORE_PLAY_PSG_PORTS

