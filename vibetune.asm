; Milestone 1A: Load display config from VTUNE.CFG if present.
; Config file format (binary, 3 bytes):
;   byte 0: magic = 0xA5
;   byte 1: DISP_MODE (0=plain, 1=VT100, 2=ANSI)
;   byte 2: reserved (ignored)
; Missing file or invalid magic → DISP_MODE stays DISP_PLAIN.
; No VT100/ANSI probing is attempted at runtime; the config file is
; the sole authority on display capability.
; Output: DISP_MODE is valid and stable for all subsequent display calls.
#DEFINE CFG_MAGIC $A5
DETECT_DISPLAY_MODE:
	; Build FCB for VTUNE.CFG in CFG_FCB
	CALL	BUILD_CFG_FCB
	; Set DMA to DMA_BUFFER (safe: structural validation not yet run)
	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS
	; Open config file (BDOS 0Fh)
	LD	DE, CFG_FCB
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, DETECT_DISP_NO_CFG	; file not found — use default
	; Read one 128-byte block (BDOS 14h)
	LD	DE, CFG_FCB
	LD	C, $14
	CALL	BDOS
	OR	A
	JR	NZ, DETECT_DISP_CLOSE	; read error — use default
	; Validate magic byte
	LD	A, (DMA_BUFFER)
	CP	CFG_MAGIC
	JR	NZ, DETECT_DISP_CLOSE
	; Load DISP_MODE from byte 1
	LD	A, (DMA_BUFFER+1)
	CP	DISP_ANSI + 1
	JR	NC, DETECT_DISP_CLOSE	; out of range — use default
	LD	(DISP_MODE), A
DETECT_DISP_CLOSE:
	; Close config file (BDOS 10h)
	LD	DE, CFG_FCB
	LD	C, $10
	CALL	BDOS
DETECT_DISP_NO_CFG:
	; Final range clamp (ensures DISP_MODE is always valid)
	LD	A, (DISP_MODE)
	CP	DISP_ANSI + 1
	JR	C, DETECT_DISP_DONE
	XOR	A
	LD	(DISP_MODE), A
DETECT_DISP_DONE:
	RET

; From CP/M page 0: high byte of BDOS vector at 7; module load stops one page below.
HEAPENDB_INIT:
	LD	A, (7)
	DEC	A
	LD	(HEAPENDB), A
	RET

; Zero player state + module area before load (VARS..HEAPEND-1).
; Starts at VARS, NOT HEAP: the parse buffers (FCB_WORK, ARG_BUFFER, ...) and
; BULBA_PORTS sit below VARS and are populated before this runs — clearing the
; whole heap would wipe the parsed filename FCB and the detected ports.
HEAP_CLEAR:
	LD	HL, VARS
	XOR	A
	LD	(HL), A
	LD	DE, VARS + 1
	LD	BC, HEAPEND - VARS - 1
	LDIR
	RET

; Build a CP/M FCB in CFG_FCB for VTUNE.CFG (drive 0, current drive).
BUILD_CFG_FCB:
	LD	HL, CFG_FCB
	LD	B, 36
BUILD_CFG_CLR:
	XOR	A
	LD	(HL), A
	INC	HL
	DJNZ	BUILD_CFG_CLR
	; Name field: "VTUNE   CFG" (8+3, space-padded)
	LD	HL, CFG_FCB + 1
	LD	DE, MSG_CFG_NAME
	LD	B, 11
BUILD_CFG_NAME:
	LD	A, (DE)
	LD	(HL), A
	INC	HL
	INC	DE
	DJNZ	BUILD_CFG_NAME
	RET

; Parse one command-line file argument and classify extension.
; If no extension is present, probe supported extensions in this order:
;   .pt3, .pt2, .mym
; Returns A = ERR_OK, ERR_NO_ARG, ERR_TOO_MANY_ARGS,
;            ERR_UNSUPPORTED_FORMAT, ERR_INVALID_FILENAME, ERR_FILE_NOT_FOUND.
PARSE_AND_CLASSIFY:
	CALL	PARSE_CMDLINE
	OR	A
	RET	NZ
	LD	A, (RUN_MODE)
	CP	RUNMODE_LIST
	JR	Z, PARSE_LIST_OK
	CALL	CHECK_LIST_SWITCH
	OR	A
	JR	Z, PARSE_CLASSIFY_FILE
PARSE_LIST_OK:
	XOR	A
	RET

PARSE_CLASSIFY_FILE:
	JP	CLASSIFY_ARG_EXTENSION

; Detect "-list" switch (case-insensitive).
; On match: sets RUN_MODE=RUNMODE_LIST and returns A=1.
; Otherwise returns A=0.
CHECK_LIST_SWITCH:
	LD	HL, ARG_BUFFER
	LD	A, (HL)
	CP	'-'
	JR	NZ, CHECK_LIST_NO
	INC	HL

	LD	A, (HL)
	CALL	TO_UPPER
	CP	'L'
	JR	NZ, CHECK_LIST_NO
	INC	HL

	LD	A, (HL)
	CALL	TO_UPPER
	CP	'I'
	JR	NZ, CHECK_LIST_NO
	INC	HL

	LD	A, (HL)
	CALL	TO_UPPER
	CP	'S'
	JR	NZ, CHECK_LIST_NO
	INC	HL

	LD	A, (HL)
	CALL	TO_UPPER
	CP	'T'
	JR	NZ, CHECK_LIST_NO
	INC	HL

	LD	A, (HL)
	OR	A
	JR	NZ, CHECK_LIST_NO

	LD	A, RUNMODE_LIST
	LD	(RUN_MODE), A
	LD	A, 1
	RET

CHECK_LIST_NO:
	XOR	A
	RET

; tune.com strings.inc STRCMP (case-sensitive) — used for -DELAY detection.
STRCMP_TUNE:
	LD	A, (DE)
	OR	A
	RET	Z
	LD	B, A
	LD	A, (HL)
	OR	A
	JR	NZ, STRCMP_TUNE1
	OR	$FF
	RET
STRCMP_TUNE1:
	CP	B
	RET	NZ
	INC	HL
	INC	DE
	JR	STRCMP_TUNE

; Bounded tune.com STRINDEX. HL = start, B = byte count, DE = needle. Z = found.
STRINDEX_TUNE_LEN:
STRINDEX_TUNE_LEN_TRY:
	LD	A, B
	OR	A
	JR	Z, STRINDEX_TUNE_LEN_FAIL
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_TUNE
	POP	DE
	POP	HL
	RET	Z
	INC	HL
	DEC	B
	JR	STRINDEX_TUNE_LEN_TRY
STRINDEX_TUNE_LEN_FAIL:
	OR	$FF
	RET

; Detect -DELAY like tune.com CLI_HAVE_DELAY_SWITCH: direct CLIARGS substring search.
; Clears DELAYMD first, then sets it only when the exact switch appears.
APPLY_DELAY_FROM_CMDLINE:
	XOR	A
	LD	(DELAYMD), A
	LD	HL, $0081
	LD	DE, MSG_SWITCH_DELAY_TUNE
	CALL	STRINDEX_TUNE
	RET	NZ
	LD	A, 1
	LD	(DELAYMD), A
	RET

; Detect -LIST directly from CLIARGS at $0081, matching the proven -DELAY path.
APPLY_LIST_FROM_CMDLINE:
	LD	HL, $0081
	LD	DE, MSG_SWITCH_LIST_TUNE
	CALL	STRINDEX_TUNE
	RET	NZ
	LD	A, RUNMODE_LIST
	LD	(RUN_MODE), A
	RET

; tune.com strings.inc STRINDEX behavior for a NUL-terminated haystack.
STRINDEX_TUNE:
	LD	B, 0
	LD	C, 0
STRINDEX_TUNE_NEXT:
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_TUNE
	POP	DE
	POP	HL
	RET	Z
	INC	HL
	INC	BC
	LD	A, (HL)
	OR	A
	JR	NZ, STRINDEX_TUNE_NEXT
	OR	$FF
	RET

; Case-insensitive substring search on raw CP/M command tail at HL.
; Stops on NUL, CR, or high-bit end-of-line marker instead of trusting $0080 length.
STRINDEX_UP_CMDTAIL:
STRINDEX_UP_CMDTAIL_TRY:
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_UP
	POP	DE
	POP	HL
	RET	Z
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, STRINDEX_UP_CMDTAIL_FAIL
	INC	HL
	JR	STRINDEX_UP_CMDTAIL_TRY
STRINDEX_UP_CMDTAIL_FAIL:
	OR	$FF
	RET

; Case-insensitive substring search within bounded haystack (B bytes at HL).
STRINDEX_UP_LEN:
STRINDEX_UP_LEN_TRY:
	LD	A, B
	OR	A
	JR	Z, STRINDEX_UP_LEN_FAIL
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_UP
	POP	DE
	POP	HL
	JR	Z, STRINDEX_UP_LEN_OK
	INC	HL
	DEC	B
	JR	STRINDEX_UP_LEN_TRY
STRINDEX_UP_LEN_FAIL:
	OR	$FF
	RET
STRINDEX_UP_LEN_OK:
	XOR	A
	RET

; Substring search in default FCB name+ext ($5D..$67, 11 bytes). Leading switches
; only (e.g. vtune -delay rl2wof). Interior NUL bytes are skipped, not fatal.
STRINDEX_FCB:
STRINDEX_FCB_TRY:
	LD	A, B
	OR	A
	JR	Z, STRINDEX_FCB_FAIL
	PUSH	HL
	PUSH	DE
	CALL	STRCMP_UP
	POP	DE
	POP	HL
	JR	Z, STRINDEX_FCB_OK
	INC	HL
	DEC	B
	JR	STRINDEX_FCB_TRY
STRINDEX_FCB_FAIL:
	OR	$FF
	RET
STRINDEX_FCB_OK:
	XOR	A
	RET

; Z = found if needle appears in bounded CLI tail or default FCB name field.
; DE = needle on entry. Uses GET_CMD_TAIL_LEN (does not require HL=$81).
SCAN_SWITCH_IN_CMD:
	PUSH	DE
	CALL	GET_CMD_TAIL_LEN
	POP	DE
	LD	A, B
	OR	A
	JR	Z, SCAN_SWITCH_FCB
	CALL	STRINDEX_UP_LEN
	RET	Z
SCAN_SWITCH_FCB:
	LD	HL, FCB + 1
	LD	B, 11
	JP	STRINDEX_FCB

; Scan command line for switches (any token order). Primary: $0081 like tune.com.
; -delay is handled only by APPLY_DELAY_FROM_CMDLINE (tune.com CLI_HAVE_DELAY_SWITCH).
SCAN_CMDLINE_SWITCHES:
	LD	DE, MSG_SWITCH_LIST
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_LIST
	LD	A, RUNMODE_LIST
	LD	(RUN_MODE), A
SCAN_SW_NO_LIST:
	LD	DE, MSG_SWITCH_MSX
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_MSX
	LD	A, HW_MODE_MSX
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_MSX:
	LD	DE, MSG_SWITCH_RC
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_RC
	LD	A, HW_MODE_RC
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_RC:
	LD	DE, MSG_SWITCH_COLECO
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_NO_COLECO
	LD	A, HW_MODE_COLECO
	LD	(HW_DETECT_MODE), A
SCAN_SW_NO_COLECO:
	LD	DE, MSG_SWITCH_EB
	CALL	SCAN_SWITCH_IN_CMD
	JR	NZ, SCAN_SW_DONE
	LD	A, HW_MODE_EB
	LD	(HW_DETECT_MODE), A
SCAN_SW_DONE:
	RET

; Z = 1 if A is NUL, CR, or CP/M end-of-line (high bit set on last byte).
CMD_CHAR_END:
	AND	$7F
	OR	A
	RET	Z
	CP	0DH
	RET

; Compare strings at HL and DE (case-insensitive). HL may end at NUL, CR, or
; CP/M high-bit delimiter. Needle (DE) drives the walk; Z = needle consumed.
STRCMP_UP:
	LD	A, (DE)
	OR	A
	JR	Z, STRCMP_UP_MATCH
	PUSH	AF
	CALL	TO_UPPER
	LD	C, A
	POP	AF
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, STRCMP_UP_NOMATCH
	PUSH	AF
	CALL	TO_UPPER
	CP	C
	POP	AF
	RET	NZ
	INC	HL
	INC	DE
	JR	STRCMP_UP
STRCMP_UP_NOMATCH:
	OR	$FF
	RET
STRCMP_UP_MATCH:
	XOR	A
	RET

; Parse CP/M command line: tune.com-style tail scan + default FCB filename.
; Returns A = error code.
PARSE_CMDLINE:
	XOR	A
	LD	(HW_DETECT_MODE), A
	LD	(ARG_HAVE), A
	LD	HL, ARG_BUFFER
	LD	B, 128

PARSE_CLR_ARG_BUF:
	LD	(HL), A
	INC	HL
	DJNZ	PARSE_CLR_ARG_BUF
	CALL	SCAN_CMDLINE_SWITCHES
	LD	A, (RUN_MODE)
	CP	RUNMODE_LIST
	JR	Z, PARSE_CL_DONE
	CALL	COPY_FCB_TO_ARG
	LD	A, (ARG_HAVE)
	LD	(PARSE_SWITCH_ONLY), A
	CALL	PARSE_TOKENS_FOR_FILENAME
	OR	A
	RET	NZ
	LD	A, (RUN_MODE)
	CP	RUNMODE_LIST
	JR	Z, PARSE_CL_DONE
	LD	A, (ARG_HAVE)
	OR	A
	JP	Z, PARSE_ERR_NO_ARG
PARSE_CL_DONE:
	XOR	A
	RET

; Copy CP/M default FCB ($5C) filename into ARG_BUFFER when usable.
; Blank or '-' first name char => leave ARG_HAVE=0 (caller uses token scan).
COPY_FCB_TO_ARG:
	XOR	A
	LD	(ARG_HAVE), A
	LD	HL, FCB+1
	LD	A, (HL)
	CP	' '
	RET	Z
	CP	'-'
	RET	Z
	LD	DE, ARG_BUFFER
	LD	B, 8

COPY_FCB_NAME:
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_NAME_SKIP
	CALL	TO_UPPER
	LD	(DE), A
	INC	DE
	INC	HL
	DJNZ	COPY_FCB_NAME
	JR	COPY_FCB_EXT

COPY_FCB_NAME_SKIP:
	INC	HL
	DJNZ	COPY_FCB_NAME

COPY_FCB_EXT:
	LD	HL, FCB+9
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_DONE
	LD	A, '.'
	LD	(DE), A
	INC	DE
	LD	B, 3

COPY_FCB_EXT_LOOP:
	LD	A, (HL)
	CP	' '
	JR	Z, COPY_FCB_DONE
	CALL	TO_UPPER
	LD	(DE), A
	INC	DE
	INC	HL
	DJNZ	COPY_FCB_EXT_LOOP

COPY_FCB_DONE:
	XOR	A
	LD	(DE), A
	LD	A, 1
	LD	(ARG_HAVE), A
	RET

; Effective command-tail length from CP/M byte $0080, clamped to first
; NUL/CR/high-bit terminator inside that declared span.
; Returns B = effective length, HL = $0081.
GET_CMD_TAIL_LEN:
	LD	A, ($0080)
	LD	D, A
	LD	HL, $0081
	LD	B, 0
GET_CMD_TAIL_CLAMP:
	LD	A, D
	OR	A
	JR	Z, GET_CMD_TAIL_DONE
	LD	A, (HL)
	CALL	CMD_CHAR_END
	JR	Z, GET_CMD_TAIL_DONE
	INC	HL
	INC	B
	DEC	D
	JR	GET_CMD_TAIL_CLAMP

GET_CMD_TAIL_DONE:
	LD	HL, $0081
	RET

; Walk command tail when FCB is blank or switch-first; take first non-switch token.
; Returns A = ERR_TOO_MANY_ARGS or ERR_OK (0).
PARSE_TOKENS_FOR_FILENAME:
	CALL	GET_CMD_TAIL_LEN

PARSE_TOK_SKIP:
	LD	A, B
	OR	A
	RET	Z
	LD	A, (HL)
	CP	' '
	JR	Z, PARSE_TOK_ADV
	CALL	CMD_CHAR_END
	JR	Z, PARSE_TOK_ADV
	JR	PARSE_TOK_TOKEN

PARSE_TOK_ADV:
	INC	HL
	DEC	B
	JR	PARSE_TOK_SKIP

PARSE_TOK_TOKEN:
	LD	DE, ARG_SCRATCH
	LD	A, (HL)
	CP	'"'
	JR	Z, PARSE_TOK_QUOTED

PARSE_TOK_UNQ:
	LD	A, B
	OR	A
	JR	Z, PARSE_TOK_DISPATCH
	LD	A, (HL)
	CP	' '
	JR	Z, PARSE_TOK_DISPATCH
	CALL	CMD_CHAR_END
	JR	Z, PARSE_TOK_DISPATCH
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	JR	PARSE_TOK_UNQ

PARSE_TOK_QUOTED:
	INC	HL
	DEC	B

PARSE_TOK_QLOOP:
	LD	A, B
	OR	A
	JR	Z, PARSE_TOK_DISPATCH
	LD	A, (HL)
	CP	'"'
	JR	Z, PARSE_TOK_QEND
	LD	(DE), A
	INC	DE
	INC	HL
	DEC	B
	JR	PARSE_TOK_QLOOP

PARSE_TOK_QEND:
	INC	HL
	DEC	B

PARSE_TOK_DISPATCH:
	XOR	A
	LD	(DE), A
	LD	HL, ARG_SCRATCH
	CALL	APPLY_IF_SWITCH
	OR	A
	JR	NZ, PARSE_TOK_SKIP_AFTER
	LD	A, (PARSE_SWITCH_ONLY)
	OR	A
	JR	NZ, PARSE_TOK_SKIP_AFTER
	LD	A, (ARG_HAVE)
	OR	A
	JP	NZ, PARSE_ERR_TOO_MANY

PARSE_TOK_TAKE_FILENAME:
	LD	A, 1
	LD	(ARG_HAVE), A
	LD	HL, ARG_SCRATCH
	LD	DE, ARG_BUFFER

PARSE_TOK_COPY:
	LD	A, (HL)
	LD	(DE), A
	OR	A
	RET	Z
	INC	HL
	INC	DE
	JR	PARSE_TOK_COPY

PARSE_TOK_SKIP_AFTER:
	JR	PARSE_TOK_SKIP

; HL = token. Apply switch flags. Returns A=1 if switch, else A=0.
APPLY_IF_SWITCH:
	LD	DE, MSG_SWITCH_LIST
	CALL	STRCMP_UP
	JR	Z, APPLY_IF_SWITCH_LIST
	LD	DE, MSG_SWITCH_MSX
	CALL	STRCMP_UP
	JR	Z, APPLY_IF_SWITCH_MSX
	LD	DE, MSG_SWITCH_RC
	CALL	STRCMP_UP
	JR	Z, APPLY_IF_SWITCH_RC
	LD	DE, MSG_SWITCH_COLECO
	CALL	STRCMP_UP
	JR	Z, APPLY_IF_SWITCH_COLECO
	LD	DE, MSG_SWITCH_EB
	CALL	STRCMP_UP
	JR	Z, APPLY_IF_SWITCH_EB
	LD	A, (HL)
	CP	'-'
	JR	Z, APPLY_IF_SWITCH_Y
	XOR	A
	RET
APPLY_IF_SWITCH_LIST:
	LD	A, RUNMODE_LIST
	LD	(RUN_MODE), A
	JR	APPLY_IF_SWITCH_Y
APPLY_IF_SWITCH_MSX:
	LD	A, HW_MODE_MSX
	LD	(HW_DETECT_MODE), A
	JR	APPLY_IF_SWITCH_Y
APPLY_IF_SWITCH_RC:
	LD	A, HW_MODE_RC
	LD	(HW_DETECT_MODE), A
	JR	APPLY_IF_SWITCH_Y
APPLY_IF_SWITCH_COLECO:
	LD	A, HW_MODE_COLECO
	LD	(HW_DETECT_MODE), A
	JR	APPLY_IF_SWITCH_Y
APPLY_IF_SWITCH_EB:
	LD	A, HW_MODE_EB
	LD	(HW_DETECT_MODE), A
	JR	APPLY_IF_SWITCH_Y
APPLY_IF_SWITCH_Y:
	LD	A, 1
	RET

PARSE_ERR_NO_ARG:
	LD	A, ERR_NO_ARG
	RET

PARSE_ERR_TOO_MANY:
	LD	A, ERR_TOO_MANY_ARGS
	RET

; Classify ARG_BUFFER extension as PTx or MYM.
; Returns A = ERR_OK or ERR_UNSUPPORTED_FORMAT.
CLASSIFY_ARG_EXTENSION:
	LD	HL, ARG_BUFFER
	LD	DE, 0

CLASS_SCAN_LOOP:
	LD	A, (HL)
	OR	A
	JR	Z, CLASS_SCAN_DONE
	CP	'.'
	JR	NZ, CLASS_SCAN_NEXT
	LD	D, H
	LD	E, L

CLASS_SCAN_NEXT:
	INC	HL
	JR	CLASS_SCAN_LOOP

CLASS_SCAN_DONE:
	LD	A, D
	OR	E
	JR	Z, CLASS_RESOLVE_MISSING_EXT
	EX	DE, HL
	INC	HL

	LD	A, (HL)
	OR	A
	JR	Z, CLASS_UNSUPPORTED
	CALL	TO_UPPER
	CP	'P'
	JR	Z, CLASS_TRY_PTX
	CP	'M'
	JR	Z, CLASS_TRY_MYM
	JR	CLASS_UNSUPPORTED

CLASS_TRY_PTX:
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'T'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	CP	'2'
	JR	Z, CLASS_PTX_END
	CP	'3'
	JR	NZ, CLASS_UNSUPPORTED

CLASS_PTX_END:
	INC	HL
	LD	A, (HL)
	OR	A
	JR	NZ, CLASS_UNSUPPORTED
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	XOR	A
	RET

CLASS_TRY_MYM:
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'Y'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	CALL	TO_UPPER
	CP	'M'
	JR	NZ, CLASS_UNSUPPORTED
	INC	HL
	LD	A, (HL)
	OR	A
	JR	NZ, CLASS_UNSUPPORTED
	LD	A, ENGINE_MYM
	LD	(FILE_ENGINE), A
	XOR	A
	RET

CLASS_UNSUPPORTED:
	LD	A, ERR_UNSUPPORTED_FORMAT
	RET

CLASS_RESOLVE_MISSING_EXT:
	JP	RESOLVE_MISSING_EXTENSION

; Resolve extensionless ARG_BUFFER by probing files in this order:
;   .PT3 -> .PT2 -> .MYM
; On success, ARG_BUFFER is updated in-place with the found extension and
; FILE_ENGINE is set accordingly.
; Returns A = ERR_OK, ERR_INVALID_FILENAME, or ERR_FILE_NOT_FOUND.
RESOLVE_MISSING_EXTENSION:
	; Find NUL terminator in ARG_BUFFER (HL points at end).
	LD	HL, ARG_BUFFER
RESOLVE_FIND_END:
	LD	DE, ARG_BUFFER + 127
	LD	A, H
	CP	D
	JR	C, RESOLVE_FIND_STEP
	JR	NZ, RESOLVE_HAVE_END
	LD	A, L
	CP	E
	JR	NC, RESOLVE_HAVE_END

RESOLVE_FIND_STEP:
	LD	A, (HL)
	OR	A
	JR	Z, RESOLVE_HAVE_END
	CP	0DH
	JR	Z, RESOLVE_HAVE_END
	INC	HL
	JR	RESOLVE_FIND_END

RESOLVE_HAVE_END:
	PUSH	HL			; keep end pointer for each candidate and final restore

	; Try .PT3 first
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_PT3
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_TRY_PT2
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_TRY_PT2:
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_PT2
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_TRY_MYM
	LD	A, ENGINE_PTX
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_TRY_MYM:
	POP	HL
	PUSH	HL
	CALL	APPEND_EXT_MYM
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, RESOLVE_FAIL_INVALID
	CALL	PROBE_FCB_EXISTS
	OR	A
	JR	Z, RESOLVE_FAIL_NOT_FOUND
	LD	A, ENGINE_MYM
	LD	(FILE_ENGINE), A
	POP	HL
	XOR	A
	RET

RESOLVE_FAIL_INVALID:
	POP	HL
	LD	(HL), 0			; restore original extensionless ARG_BUFFER
	LD	A, ERR_INVALID_FILENAME
	RET

RESOLVE_FAIL_NOT_FOUND:
	POP	HL
	LD	(HL), 0			; restore original extensionless ARG_BUFFER
	LD	A, ERR_FILE_NOT_FOUND
	RET

; Append ".PT3" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_PT3:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'P'
	INC	HL
	LD	(HL), 'T'
	INC	HL
	LD	(HL), '3'
	INC	HL
	LD	(HL), 0
	RET

; Append ".PT2" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_PT2:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'P'
	INC	HL
	LD	(HL), 'T'
	INC	HL
	LD	(HL), '2'
	INC	HL
	LD	(HL), 0
	RET

; Append ".MYM" at end pointer HL (which must point to trailing NUL).
APPEND_EXT_MYM:
	LD	(HL), '.'
	INC	HL
	LD	(HL), 'M'
	INC	HL
	LD	(HL), 'Y'
	INC	HL
	LD	(HL), 'M'
	INC	HL
	LD	(HL), 0
	RET

; Probe FCB_WORK existence by open/close.
; Returns A=1 if file exists, A=0 if missing.
PROBE_FCB_EXISTS:
	LD	DE, FCB_WORK
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, PROBE_FCB_MISS
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	LD	A, 1
	RET

PROBE_FCB_MISS:
	XOR	A
	RET

; Stage 2 validation: build CP/M FCB from argument and verify open/read path.
; Returns A = ERR_OK, ERR_INVALID_FILENAME, ERR_FILE_NOT_FOUND, ERR_FILE_READ.
VALIDATE_FILE_ACCESS:
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	RET	NZ

	LD	DE, FCB_WORK
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, VALIDATE_FILE_MISSING

	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS

	LD	DE, FCB_WORK
	LD	C, $14
	CALL	BDOS
	CP	0
	JR	Z, VALIDATE_FILE_CLOSE_OK
	CP	1
	JR	Z, VALIDATE_FILE_CLOSE_OK

	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	LD	A, ERR_FILE_READ
	RET

VALIDATE_FILE_CLOSE_OK:
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	XOR	A
	RET

VALIDATE_FILE_MISSING:
	LD	A, ERR_FILE_NOT_FOUND
	RET

; Stage 2 lightweight structural checks from first DMA block.
; Returns A = ERR_OK or ERR_INVALID_DATA.
VALIDATE_FORMAT_STRUCTURE:
	LD	A, (FILE_ENGINE)
	CP	ENGINE_MYM
	JR	Z, VALIDATE_MYM_STRUCTURE
	CP	ENGINE_PTX
	JR	Z, VALIDATE_PTX_STRUCTURE
	LD	A, ERR_INVALID_DATA
	RET

VALIDATE_MYM_STRUCTURE:
	LD	A, (DMA_BUFFER)
	CP	$92
	JP	NZ, VALIDATE_FORMAT_INVALID
	LD	A, (DMA_BUFFER+1)
	OR	A
	JP	Z, VALIDATE_FORMAT_INVALID
	CP	64
	JP	NC, VALIDATE_FORMAT_INVALID
	XOR	A
	RET

VALIDATE_PTX_STRUCTURE:
	CALL	PTX_PRINTABLE_PREFIX
	OR	A
	JP	NZ, VALIDATE_FORMAT_INVALID
	CALL	PTX_MATCH_VORTEX_HEADER
	OR	A
	JR	Z, VALIDATE_PTX_OK
	CALL	PTX_MATCH_PROTRACKER_HEADER
	OR	A
	JP	NZ, VALIDATE_FORMAT_INVALID

VALIDATE_PTX_OK:
	XOR	A
	RET

PTX_PRINTABLE_PREFIX:
	LD	HL, DMA_BUFFER
	LD	B, 16

PTX_PRINTABLE_LOOP:
	LD	A, (HL)
	CALL	IS_PRINTABLE_ASCII
	JR	NZ, PTX_PRINTABLE_BAD
	INC	HL
	DJNZ	PTX_PRINTABLE_LOOP
	XOR	A
	RET

PTX_PRINTABLE_BAD:
	LD	A, 1
	RET

PTX_MATCH_VORTEX_HEADER:
	LD	HL, DMA_BUFFER
	JR	PTX_MATCH_VORTEX_HL

PTX_MATCH_VORTEX_MUSIC:
	LD	HL, MUSIC_BUF

PTX_MATCH_VORTEX_HL:
	LD	A, (HL)
	CP	'V'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'o'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	't'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'e'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'x'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	' '
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'T'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'a'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'c'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'k'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'e'
	JR	NZ, PTX_VORTEX_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	XOR	A
	RET

PTX_VORTEX_BAD:
	LD	A, 1
	RET

PTX_MATCH_PROTRACKER_HEADER:
	LD	HL, DMA_BUFFER
	JR	PTX_MATCH_PROTRACKER_HL

PTX_MATCH_PROTRACKER_MUSIC:
	LD	HL, MUSIC_BUF

PTX_MATCH_PROTRACKER_HL:
	LD	A, (HL)
	CP	'P'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'o'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'T'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'a'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'c'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'k'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'e'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	' '
	JR	NZ, PTX_PROTRACKER_BAD
	XOR	A
	RET

PTX_PROTRACKER_BAD:
	LD	A, 1
	RET

IS_PRINTABLE_ASCII:
	CP	32
	JR	C, IS_PRINTABLE_BAD
	CP	127
	JR	NC, IS_PRINTABLE_BAD
	XOR	A
	RET

IS_PRINTABLE_BAD:
	LD	A, 1
	RET

VALIDATE_FORMAT_INVALID:
	LD	A, ERR_INVALID_DATA
	RET

; Stage 3 validation: engine-specific initialization checkpoint.
; Returns A = ERR_OK, ERR_INVALID_DATA, or ERR_ENGINE_INIT.
ENGINE_INIT:
	LD	A, (FILE_ENGINE)
	CP	ENGINE_PTX
	JP	Z, ENGINE_INIT_PTX
	CP	ENGINE_MYM
	JP	Z, ENGINE_INIT_MYM
	LD	A, ERR_INVALID_DATA
	RET

ENGINE_INIT_PTX:
	CALL	PTX_MATCH_VORTEX_MUSIC
	OR	A
	JP	Z, ENGINE_INIT_PTX_VORTEX
	CALL	PTX_MATCH_PROTRACKER_MUSIC
	OR	A
	JP	Z, ENGINE_INIT_PTX_PROTRACKER
	LD	A, ERR_INVALID_DATA
	RET

ENGINE_INIT_PTX_VORTEX:
	LD	A, PTX_VARIANT_VORTEX
	LD	(PTX_VARIANT), A
	JR	ENGINE_INIT_PTX_BULBA

ENGINE_INIT_PTX_PROTRACKER:
	LD	A, PTX_VARIANT_PROTRACKER
	LD	(PTX_VARIANT), A

ENGINE_INIT_PTX_BULBA:
	XOR	A
	LD	(TSFLAG), A
	LD	(TS_DUALHW), A
	LD	(TS_OFF2), A
	LD	(TS_OFF2+1), A
	XOR	A
	LD	(PTX_STATE_POS), A
	LD	(PTX_STATE_POS+1), A
	CALL	BULBA_SYNC_PORTS
	CALL	PSG_MUTE_DIRECT		; Clean PSG state before engine init
	CALL	PTX_DETECT_TURBOSOUND
	OR	A
	JR	Z, ENGINE_INIT_PTX_SINGLE
	CALL	TS_PORTS_SETUP
	LD	A, (TS_DUALHW)
	OR	A
	JR	Z, ENGINE_INIT_PTX_SINGLE
	CALL	TS_INIT
	XOR	A
	RET

ENGINE_INIT_PTX_SINGLE:
	XOR	A
	LD	(BULBA_START + 10), A
	CALL	BULBA_START
	XOR	A
	RET

ENGINE_INIT_MYM:
	LD	A, (DMA_BUFFER+1)
	LD	(MYM_FRAME_HINT), A
	; Reset MYM frame pointer to start of MUSIC_BUF
	LD	HL, MUSIC_BUF
	LD	(MYM_STATE_PTR), HL
	XOR	A
	RET

; Milestone 3: Scan current drive for .PT2/.PT3/.MYM files.
; Fills TRACK_LIST with NUL-terminated 8.3 name strings (TRACK_NAME_LEN each).
; Sets TRACK_COUNT. Returns A = count.
; Ordering follows CP/M directory slot order which is deterministic per disk image.
SCAN_TRACKS:
	XOR	A
	LD	(TRACK_COUNT), A
	LD	(TRACK_SELECTED), A

	; Clear wildcard FCB
	LD	HL, SCAN_FCB
	LD	B, 36
SCAN_FCB_CLR:
	XOR	A
	LD	(HL), A
	INC	HL
	DJNZ	SCAN_FCB_CLR

	; Fill name+ext fields with '?'
	LD	HL, SCAN_FCB+1
	LD	B, 11
SCAN_FCB_WILD:
	LD	(HL), '?'
	INC	HL
	DJNZ	SCAN_FCB_WILD

	; Set DMA to DMA_BUFFER
	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS

	; Search first
	LD	DE, SCAN_FCB
	LD	C, $11
	CALL	BDOS
	CP	$FF
	JP	Z, SCAN_DONE

SCAN_LOOP:
	; A = entry index (0-3) in DMA_BUFFER; each entry = 32 bytes
	LD	L, A
	LD	H, 0
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	LD	DE, DMA_BUFFER
	ADD	HL, DE

	; Skip deleted entries ($E5).
	; Do not force user 0 here: BDOS search already scopes to current user area.
	LD	A, (HL)
	CP	$E5
	JP	Z, SCAN_NEXT

	; Extract name/ext, check for supported extension
	PUSH	HL
	CALL	EXTRACT_TRACK_NAME
	POP	HL
	OR	A
	JP	Z, SCAN_NEXT

	; Deduplicate: skip if already in list
	CALL	TRACK_LIST_FIND
	OR	A
	JP	NZ, SCAN_NEXT

	; Add to track list
	CALL	TRACK_LIST_ADD

SCAN_NEXT:
	LD	DE, SCAN_FCB
	LD	C, $12
	CALL	BDOS
	CP	$FF
	JP	Z, SCAN_DONE
	JP	SCAN_LOOP

SCAN_DONE:
	; Restore DMA to default ($0080) before returning from scan.
	; The DMA was set to DMA_BUFFER during BDOS 11h/12h calls; if we don't restore it,
	; any subsequent BDOS call may read/write wrong location, corrupting memory.
	LD	DE, $0080
	LD	C, $1A
	CALL	BDOS
	LD	A, (TRACK_COUNT)
	RET

; Extract name from directory entry at HL into SCAN_NAME_BUF.
; Checks extension against PT2/PT3/MYM.
; Returns A=1 if supported, A=0 if not.
EXTRACT_TRACK_NAME:
	PUSH	BC
	PUSH	DE
	PUSH	HL

	INC	HL		; skip user byte
	LD	DE, SCAN_NAME_BUF
	LD	B, 8

EXTR_NAME_LOOP:
	LD	A, (HL)
	INC	HL		; always advance
	AND	$7F		; strip attribute bit
	CP	' '
	JR	Z, EXTR_NAME_SKIP
	LD	(DE), A
	INC	DE
EXTR_NAME_SKIP:
	DJNZ	EXTR_NAME_LOOP

	; HL now points to ext[0]; copy 3 ext bytes to SCAN_EXT_BUF
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF), A
	INC	HL
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF+1), A
	INC	HL
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF+2), A

	; Check: PT2
	LD	A, (SCAN_EXT_BUF)
	CP	'P'
	JR	NZ, EXTR_TRY_MYM
	LD	A, (SCAN_EXT_BUF+1)
	CP	'T'
	JR	NZ, EXTR_TRY_MYM
	LD	A, (SCAN_EXT_BUF+2)
	CP	'2'
	JR	Z, EXTR_EXT_OK
	CP	'3'
	JR	Z, EXTR_EXT_OK
	JR	EXTR_UNSUPPORTED

EXTR_TRY_MYM:
	LD	A, (SCAN_EXT_BUF)
	CP	'M'
	JR	NZ, EXTR_UNSUPPORTED
	LD	A, (SCAN_EXT_BUF+1)
	CP	'Y'
	JR	NZ, EXTR_UNSUPPORTED
	LD	A, (SCAN_EXT_BUF+2)
	CP	'M'
	JR	NZ, EXTR_UNSUPPORTED

EXTR_EXT_OK:
	; Append '.' + 3 ext chars + NUL to DE
	LD	A, '.'
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF)
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF+1)
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF+2)
	LD	(DE), A
	INC	DE
	XOR	A
	LD	(DE), A
	POP	HL
	POP	DE
	POP	BC
	LD	A, 1
	RET

EXTR_UNSUPPORTED:
	POP	HL
	POP	DE
	POP	BC
	XOR	A
	RET

; Search TRACK_LIST for SCAN_NAME_BUF.
; Returns A=1 if found, A=0 if not.
TRACK_LIST_FIND:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, TRACK_FIND_NOTFOUND
	LD	B, A
	LD	HL, TRACK_LIST

TRACK_FIND_LOOP:
	LD	DE, SCAN_NAME_BUF
	PUSH	HL
	PUSH	BC
	LD	B, TRACK_NAME_LEN

TRACK_CMP_LOOP:
	LD	A, (DE)
	CP	(HL)
	JR	NZ, TRACK_CMP_MISS
	OR	A
	JR	Z, TRACK_CMP_MATCH
	INC	HL
	INC	DE
	DJNZ	TRACK_CMP_LOOP

TRACK_CMP_MATCH:
	POP	BC
	POP	HL
	LD	A, 1
	RET

TRACK_CMP_MISS:
	POP	BC
	POP	HL
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	DJNZ	TRACK_FIND_LOOP

TRACK_FIND_NOTFOUND:
	XOR	A
	RET

; Add SCAN_NAME_BUF to TRACK_LIST if not full.
TRACK_LIST_ADD:
	LD	A, (TRACK_COUNT)
	CP	MAX_TRACKS
	RET	NC
	; Compute destination: TRACK_LIST + count * TRACK_NAME_LEN
	LD	B, A
	LD	HL, 0
TRACK_ADD_MUL:
	LD	A, B
	OR	A
	JR	Z, TRACK_ADD_MUL_DONE
	DEC	B
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	JR	TRACK_ADD_MUL
TRACK_ADD_MUL_DONE:
	LD	DE, TRACK_LIST
	ADD	HL, DE
	; Copy SCAN_NAME_BUF to HL (TRACK_NAME_LEN bytes)
	LD	DE, SCAN_NAME_BUF
	LD	B, TRACK_NAME_LEN
TRACK_ADD_COPY:
	LD	A, (DE)
	LD	(HL), A
	INC	HL
	INC	DE
	DJNZ	TRACK_ADD_COPY
	LD	HL, TRACK_COUNT
	INC	(HL)
	RET

; Print all tracks in TRACK_LIST.
; Selected item (index == TRACK_SELECTED) is prefixed with "> ".
; All others are prefixed with "  ".
PRINT_TRACK_LIST:
	LD	A, (TRACK_COUNT)
	OR	A
	RET	Z
	LD	B, A		; B = loop counter (TRACK_COUNT down to 1)
	LD	C, 0		; C = current 0-based index
	LD	HL, TRACK_LIST

PRINT_TRACK_LOOP:
	PUSH	BC
	PUSH	HL
	; Compare C (current index) to TRACK_SELECTED
	LD	A, (TRACK_SELECTED)
	CP	C
	JR	NZ, PRINT_TRACK_UNSEL
	LD	A, '>'
	CALL	PRTCHR
	LD	A, ' '
	CALL	PRTCHR
	JR	PRINT_TRACK_NAME
PRINT_TRACK_UNSEL:
	LD	A, ' '
	CALL	PRTCHR
	LD	A, ' '
	CALL	PRTCHR
PRINT_TRACK_NAME:
	LD	D, H
	LD	E, L
	CALL	PRTSTR
	CALL	CRLF
	POP	HL
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	POP	BC
	INC	C		; advance 0-based index
	DJNZ	PRINT_TRACK_LOOP
	RET

; Print A as decimal (0-99).
PRINT_DECIMAL_BYTE:
	LD	B, 0
PRINT_DEC_TENS:
	CP	10
	JR	C, PRINT_DEC_EMIT
	SUB	10
	INC	B
	JR	PRINT_DEC_TENS
PRINT_DEC_EMIT:
	PUSH	AF
	LD	A, B
	OR	A
	JR	Z, PRINT_DEC_UNITS
	ADD	A, '0'
	CALL	PRTCHR
PRINT_DEC_UNITS:
	POP	AF
	ADD	A, '0'
	JP	PRTCHR

