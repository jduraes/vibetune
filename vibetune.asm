; Print the character in A via CP/M BDOS function 2. Preserves AF (some BDOS
; builds return A=0, which would corrupt decimal/ANSI emit loops).
PRTCHR:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E, A
	LD	C, $02
	CALL	BDOS
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET

