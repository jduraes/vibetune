	CP	' '
	JR	NZ, PTX_PROTRACKER_BAD
	XOR	A
	RET

PTX_PROTRACKER_BAD:
	LD	A, 1
	RET

IS_PRINTABLE_ASCII:
	CP	32
	JR	C, IS_PRINTABLE_BAD
	CP	127
	JR	NC, IS_PRINTABLE_BAD
	XOR	A
	RET

IS_PRINTABLE_BAD:
	LD	A, 1
	RET

VALIDATE_FORMAT_INVALID:
	LD	A, ERR_INVALID_DATA
	RET

; Stage 3 validation: engine-specific initialization checkpoint.
; Returns A = ERR_OK, ERR_INVALID_DATA, or ERR_ENGINE_INIT.
ENGINE_INIT:
	LD	A, (FILE_ENGINE)
	CP	ENGINE_PTX
	JP	Z, ENGINE_INIT_PTX
	CP	ENGINE_MYM
	JP	Z, ENGINE_INIT_MYM
	LD	A, ERR_INVALID_DATA
	RET

ENGINE_INIT_PTX:
	CALL	PTX_MATCH_VORTEX_MUSIC
	OR	A
	JP	Z, ENGINE_INIT_PTX_VORTEX
	CALL	PTX_MATCH_PROTRACKER_MUSIC
	OR	A
	JP	Z, ENGINE_INIT_PTX_PROTRACKER
	LD	A, ERR_INVALID_DATA
	RET

ENGINE_INIT_PTX_VORTEX:
	LD	A, PTX_VARIANT_VORTEX
	LD	(PTX_VARIANT), A
	JR	ENGINE_INIT_PTX_BULBA

ENGINE_INIT_PTX_PROTRACKER:
	LD	A, PTX_VARIANT_PROTRACKER
	LD	(PTX_VARIANT), A

ENGINE_INIT_PTX_BULBA:
	; Mute using still-valid TSFLAG/TS_DUALHW from the previous track,
	; then clear those flags for the new init.
	CALL	START_EXIT_SILENCE
	XOR	A
	LD	(PTX_DONE), A
	LD	(TSFLAG), A
	LD	(TS_DUALHW), A
	LD	(TS_OFF2), A
	LD	(TS_OFF2+1), A
	XOR	A
	LD	(PTX_STATE_POS), A
	LD	(PTX_STATE_POS+1), A
	CALL	BULBA_SYNC_PORTS
	CALL	PTX_DETECT_TURBOSOUND
	OR	A
	JR	Z, ENGINE_INIT_PTX_SINGLE
	CALL	TS_PORTS_SETUP
	LD	A, (TS_DUALHW)
	OR	A
	JR	Z, ENGINE_INIT_PTX_SINGLE
	CALL	TS_INIT
	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	CALL	Z, TSMOD_MUTE		; both virtual chips; INIT ROUT is per-chip only
	XOR	A
	RET

ENGINE_INIT_PTX_SINGLE:
	; Playlist re-init: prior track has mutated Bulba self-mod. Dual TS_INIT
	; reloads TS_CTXTMPL; single path must too or INIT jumps into garbage
	; (crash on RL2WOF→RL2WOFTS when module dual is refused).
	CALL	TS_END_DUAL_SESSION
	CALL	TS_LOAD_TMPL
	LD	A, BULBA_SETUP_INIT
	LD	(BULBA_START + 10), A
	CALL	BULBA_START
	XOR	A
	RET

ENGINE_INIT_MYM:
	CALL	TS_END_DUAL_SESSION
	CALL	MYM_INIT
	CALL	MYM_EXTRACT		; prime depack window A
	LD	(MYM_NEXT_SRC), IY
	CALL	MYM_EXTRACT		; prime depack window B
	LD	(MYM_NEXT_SRC), IY
	XOR	A
	RET

; Milestone 3: Scan current drive for .PT2/.PT3/.MYM files.
; Fills TRACK_LIST with NUL-terminated 8.3 name strings (TRACK_NAME_LEN each).
; Sets TRACK_COUNT. Returns A = count.
; Ordering follows CP/M directory slot order which is deterministic per disk image.
SCAN_TRACKS:
	XOR	A
	LD	(TRACK_COUNT), A
	LD	(TRACK_SELECTED), A

	; Clear wildcard FCB
	LD	HL, SCAN_FCB
	LD	B, 36
SCAN_FCB_CLR:
	XOR	A
	LD	(HL), A
	INC	HL
	DJNZ	SCAN_FCB_CLR

	; Fill name+ext fields with '?'
	LD	HL, SCAN_FCB+1
	LD	B, 11
SCAN_FCB_WILD:
	LD	(HL), '?'
	INC	HL
	DJNZ	SCAN_FCB_WILD

	; Set DMA to DMA_BUFFER
	LD	DE, DMA_BUFFER
	LD	C, $1A
	CALL	BDOS

	; Search first
	LD	DE, SCAN_FCB
	LD	C, $11
	CALL	BDOS
	CP	$FF
	JP	Z, SCAN_DONE

SCAN_LOOP:
	; A = entry index (0-3) in DMA_BUFFER; each entry = 32 bytes
	LD	L, A
	LD	H, 0
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	ADD	HL, HL
	LD	DE, DMA_BUFFER
	ADD	HL, DE

	; Skip deleted entries ($E5).
	; Do not force user 0 here: BDOS search already scopes to current user area.
	LD	A, (HL)
	CP	$E5
	JP	Z, SCAN_NEXT

	; Extract name/ext, check for supported extension
	PUSH	HL
	CALL	EXTRACT_TRACK_NAME
	POP	HL
	OR	A
	JP	Z, SCAN_NEXT

	; Deduplicate: skip if already in list
	CALL	TRACK_LIST_FIND
	OR	A
	JP	NZ, SCAN_NEXT

	; Add to track list
	CALL	TRACK_LIST_ADD

SCAN_NEXT:
	LD	DE, SCAN_FCB
	LD	C, $12
	CALL	BDOS
	CP	$FF
	JP	Z, SCAN_DONE
	JP	SCAN_LOOP

SCAN_DONE:
	; Restore DMA to default ($0080) before returning from scan.
	; The DMA was set to DMA_BUFFER during BDOS 11h/12h calls; if we don't restore it,
	; any subsequent BDOS call may read/write wrong location, corrupting memory.
	LD	DE, $0080
	LD	C, $1A
	CALL	BDOS
	LD	A, (TRACK_COUNT)
	RET

; Extract name from directory entry at HL into SCAN_NAME_BUF.
; Checks extension against PT2/PT3/MYM.
; Returns A=1 if supported, A=0 if not.
EXTRACT_TRACK_NAME:
	PUSH	BC
	PUSH	DE
	PUSH	HL

	INC	HL		; skip user byte
	LD	DE, SCAN_NAME_BUF
	LD	B, 8

EXTR_NAME_LOOP:
	LD	A, (HL)
	INC	HL		; always advance
	AND	$7F		; strip attribute bit
	CP	' '
	JR	Z, EXTR_NAME_SKIP
	LD	(DE), A
	INC	DE
EXTR_NAME_SKIP:
	DJNZ	EXTR_NAME_LOOP

	; HL now points to ext[0]; copy 3 ext bytes to SCAN_EXT_BUF
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF), A
	INC	HL
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF+1), A
	INC	HL
	LD	A, (HL)
	AND	$7F
	LD	(SCAN_EXT_BUF+2), A

	; Check: PT2
	LD	A, (SCAN_EXT_BUF)
	CP	'P'
	JR	NZ, EXTR_TRY_MYM
	LD	A, (SCAN_EXT_BUF+1)
	CP	'T'
	JR	NZ, EXTR_TRY_MYM
	LD	A, (SCAN_EXT_BUF+2)
	CP	'2'
	JR	Z, EXTR_EXT_OK
	CP	'3'
	JR	Z, EXTR_EXT_OK
	JR	EXTR_UNSUPPORTED

EXTR_TRY_MYM:
	LD	A, (SCAN_EXT_BUF)
	CP	'M'
	JR	NZ, EXTR_UNSUPPORTED
	LD	A, (SCAN_EXT_BUF+1)
	CP	'Y'
	JR	NZ, EXTR_UNSUPPORTED
	LD	A, (SCAN_EXT_BUF+2)
	CP	'M'
	JR	NZ, EXTR_UNSUPPORTED

EXTR_EXT_OK:
	; Append '.' + 3 ext chars + NUL to DE
	LD	A, '.'
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF)
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF+1)
	LD	(DE), A
	INC	DE
	LD	A, (SCAN_EXT_BUF+2)
	LD	(DE), A
	INC	DE
	XOR	A
	LD	(DE), A
	POP	HL
	POP	DE
	POP	BC
	LD	A, 1
	RET

EXTR_UNSUPPORTED:
	POP	HL
	POP	DE
	POP	BC
	XOR	A
	RET

; Search TRACK_LIST for SCAN_NAME_BUF.
; Returns A=1 if found, A=0 if not.
TRACK_LIST_FIND:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, TRACK_FIND_NOTFOUND
	LD	B, A
	LD	HL, TRACK_LIST

TRACK_FIND_LOOP:
	LD	DE, SCAN_NAME_BUF
	PUSH	HL
	PUSH	BC
	LD	B, TRACK_NAME_LEN

TRACK_CMP_LOOP:
	LD	A, (DE)
	CP	(HL)
	JR	NZ, TRACK_CMP_MISS
	OR	A
	JR	Z, TRACK_CMP_MATCH
	INC	HL
	INC	DE
	DJNZ	TRACK_CMP_LOOP

TRACK_CMP_MATCH:
	POP	BC
	POP	HL
	LD	A, 1
	RET

TRACK_CMP_MISS:
	POP	BC
	POP	HL
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	DJNZ	TRACK_FIND_LOOP

TRACK_FIND_NOTFOUND:
	XOR	A
	RET

; Add SCAN_NAME_BUF to TRACK_LIST if not full.
TRACK_LIST_ADD:
	LD	A, (TRACK_COUNT)
	CP	MAX_TRACKS
	RET	NC
	; Compute destination: TRACK_LIST + count * TRACK_NAME_LEN
	LD	B, A
	LD	HL, 0
TRACK_ADD_MUL:
	LD	A, B
	OR	A
	JR	Z, TRACK_ADD_MUL_DONE
	DEC	B
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	JR	TRACK_ADD_MUL
TRACK_ADD_MUL_DONE:
	LD	DE, TRACK_LIST
	ADD	HL, DE
	; Copy SCAN_NAME_BUF to HL (TRACK_NAME_LEN bytes)
	LD	DE, SCAN_NAME_BUF
	LD	B, TRACK_NAME_LEN
TRACK_ADD_COPY:
	LD	A, (DE)
	LD	(HL), A
	INC	HL
	INC	DE
	DJNZ	TRACK_ADD_COPY
	LD	HL, TRACK_COUNT
	INC	(HL)
	RET

; Print all tracks in TRACK_LIST.
; Selected item (index == TRACK_SELECTED) is prefixed with "> ".
; All others are prefixed with "  ".
PRINT_TRACK_LIST:
	LD	A, (TRACK_COUNT)
	OR	A
	RET	Z
	LD	B, A		; B = loop counter (TRACK_COUNT down to 1)
	LD	C, 0		; C = current 0-based index
	LD	HL, TRACK_LIST

PRINT_TRACK_LOOP:
	PUSH	BC
	PUSH	HL
	; Compare C (current index) to TRACK_SELECTED
	LD	A, (TRACK_SELECTED)
	CP	C
	JR	NZ, PRINT_TRACK_UNSEL
	LD	A, '>'
	CALL	PRTCHR
	LD	A, ' '
	CALL	PRTCHR
	JR	PRINT_TRACK_NAME
PRINT_TRACK_UNSEL:
	LD	A, ' '
	CALL	PRTCHR
	LD	A, ' '
	CALL	PRTCHR
PRINT_TRACK_NAME:
	LD	D, H
	LD	E, L
	CALL	PRTSTR
	CALL	CRLF
	POP	HL
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	POP	BC
	INC	C		; advance 0-based index
	DJNZ	PRINT_TRACK_LOOP
	RET

; Print A as decimal (0-99).
PRINT_DECIMAL_BYTE:
	LD	B, 0
PRINT_DEC_TENS:
	CP	10
	JR	C, PRINT_DEC_EMIT
	SUB	10
	INC	B
	JR	PRINT_DEC_TENS
PRINT_DEC_EMIT:
	PUSH	AF
	LD	A, B
	OR	A
	JR	Z, PRINT_DEC_UNITS
	ADD	A, '0'
	CALL	PRTCHR
PRINT_DEC_UNITS:
	POP	AF
	ADD	A, '0'
	JP	PRTCHR

