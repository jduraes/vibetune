	CP	'r'
	JR	NZ, PTX_VORTEX_BAD
	XOR	A
	RET

PTX_VORTEX_BAD:
	LD	A, 1
	RET

PTX_MATCH_PROTRACKER_HEADER:
	LD	HL, DMA_BUFFER
	JR	PTX_MATCH_PROTRACKER_HL

PTX_MATCH_PROTRACKER_MUSIC:
	LD	HL, MUSIC_BUF

PTX_MATCH_PROTRACKER_HL:
	LD	A, (HL)
	CP	'P'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'o'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'T'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'r'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'a'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'c'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'k'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
	CP	'e'
	JR	NZ, PTX_PROTRACKER_BAD
	INC	HL
	LD	A, (HL)
