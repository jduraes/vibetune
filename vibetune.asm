	LD	B, 0
	LDIR
	LD	BC, 3
	ADD	IX, BC
	JR	CTX_LLP

;-------------------------------------------------------------------------------
; Milestone 5: MYM engine tick
; MYM format: 14 AY register bytes per frame, frames stored interleaved.
; State: MYM_STATE_PTR (2 bytes) = pointer to current frame in MUSIC_BUF.
; Each tick: write registers 0-13 from current frame, advance pointer by 14.
; Stops (silences) when pointer exceeds MUSIC_BUF + MUSIC_SIZE.
;-------------------------------------------------------------------------------
#DEFINE MYM_FRAME_SIZE 14

MYM_ENGINE_TICK:
	; Load current frame pointer
	LD	HL, (MYM_STATE_PTR)
	; Check end of data: HL >= MUSIC_BUF + MUSIC_SIZE?
	LD	DE, (MUSIC_SIZE)
	LD	BC, MUSIC_BUF
	; end_ptr = MUSIC_BUF + MUSIC_SIZE
	LD	A, C
	ADD	A, E
	LD	E, A
	LD	A, B
	ADC	A, D
	LD	D, A		; DE = end_ptr
	; Compare HL >= DE
	LD	A, H
	CP	D
	JR	C, MYM_WRITE_FRAME	; HL < DE: still data
	JR	NZ, MYM_TICK_STOP	; HL > DE: past end
	LD	A, L
	CP	E
	JR	NC, MYM_TICK_STOP	; HL >= DE: at or past end

MYM_WRITE_FRAME:
	PUSH	HL
	CALL	PSG_ROUT_BLOCK
	POP	HL
	LD	DE, MYM_FRAME_SIZE
	ADD	HL, DE
	LD	(MYM_STATE_PTR), HL
	JP	PLAYBACK_TICK_DONE

MYM_TICK_STOP:
	CALL	PSG_SILENCE
	LD	A, PLAY_STOPPED
	LD	(PLAY_STATE), A
	JP	PLAYBACK_TICK_DONE

;===============================================================================
; Milestone 6: Main playback loop, keystroke dispatch, loop/nav state
;===============================================================================

; Main playback loop. Entered after LOAD_MUSIC_FILE succeeds.
; Each iteration: tick engine, poll key, dispatch action, frame delay.
; Exits when PLAY_STOPPED and no restart needed, or on quit.
MAIN_LOOP:
	CALL	PLAYBACK_TICK

	; Non-blocking key poll (same as tune.com: BDOS 06h direct, E=FF).
	LD	C, $06
	LD	E, $FF
	CALL	BDOS
	OR	A
	JP	Z, MAIN_LOOP_NODELAY
	AND	$7F
	OR	A
	JP	Z, MAIN_LOOP_NODELAY

	; Key dispatch
	CP	KEY_QUIT
	JP	Z, MAIN_QUIT
	CP	KEY_QUIT_L
	JP	Z, MAIN_QUIT
	CP	KEY_QUIT_ESC
	JP	Z, MAIN_QUIT
	CP	KEY_QUIT_CTRL_C
	JP	Z, MAIN_QUIT
	CP	KEY_PAUSE
	JP	Z, MAIN_PAUSE_TOGGLE
	CP	KEY_NEXT
	JP	Z, MAIN_NEXT
	CP	KEY_NEXT_L
	JP	Z, MAIN_NEXT
	CP	KEY_PREV
	JP	Z, MAIN_PREV
	CP	KEY_PREV_L
	JP	Z, MAIN_PREV
	CP	KEY_LOOP
	JP	Z, MAIN_LOOP_TOGGLE
	CP	KEY_LOOP_L
	JP	Z, MAIN_LOOP_TOGGLE
	JP	MAIN_LOOP_NODELAY

MAIN_QUIT:
	CALL	FLUSH_KEYS
	JP	START_EXIT

MAIN_PAUSE_TOGGLE:
	LD	A, (PLAY_STATE)
	CP	PLAY_PLAYING
	JR	NZ, MAIN_RESUME
	LD	A, PLAY_PAUSED
	LD	(PLAY_STATE), A
	CALL	PSG_MIXER_OFF
	LD	A, STATUS_PAUSED
	LD	(STATUS_MSG_PENDING), A
	JR	MAIN_LOOP_NODELAY
MAIN_RESUME:
	CP	PLAY_PAUSED
	JR	NZ, MAIN_LOOP_NODELAY
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
	LD	A, STATUS_PLAYING
	LD	(STATUS_MSG_PENDING), A
	JR	MAIN_LOOP_NODELAY

MAIN_NEXT:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_NODELAY
	LD	A, (TRACK_SELECTED)
	INC	A
	LD	HL, TRACK_COUNT
	CP	(HL)
	JR	C, MAIN_NEXT_OK
	XOR	A				; wrap to 0
MAIN_NEXT_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_RELOAD_TRACK

MAIN_PREV:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_NODELAY
	LD	A, (TRACK_SELECTED)
	OR	A
	JR	NZ, MAIN_PREV_DEC
	LD	A, (TRACK_COUNT)
	DEC	A				; wrap to last
	JR	MAIN_PREV_OK
MAIN_PREV_DEC:
	DEC	A
MAIN_PREV_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_RELOAD_TRACK

MAIN_LOOP_TOGGLE:
	LD	A, (LOOP_MODE)
	INC	A
	CP	LOOP_PLAYLIST + 1
	JR	C, MAIN_LOOP_TOGGLE_OK
	XOR	A
MAIN_LOOP_TOGGLE_OK:
	LD	(LOOP_MODE), A
	INC	A
	LD	(STATUS_MSG_PENDING), A
	JR	MAIN_LOOP_NODELAY

MAIN_LOOP_NODELAY:
	CALL	WAITQ
	CALL	PRINT_DEFERRED_STATUS

	; Check if stopped: handle loop/next logic
	LD	A, (PLAY_STATE)
	CP	PLAY_STOPPED
	JP	NZ, MAIN_LOOP		; still playing/paused — iterate
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_END		; direct-file playback: stop means exit
	; Track ended. Check loop mode.
	LD	A, (LOOP_MODE)
	CP	LOOP_TRACK
	JR	Z, MAIN_RELOAD_TRACK	; loop current track
	CP	LOOP_PLAYLIST
	JR	NZ, MAIN_LOOP_END	; no loop — done
	; Playlist loop: advance to next, wrap
	LD	A, (TRACK_SELECTED)
	INC	A
	LD	HL, TRACK_COUNT
	CP	(HL)
	JR	C, MAIN_PLAYLIST_OK
	XOR	A
MAIN_PLAYLIST_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_RELOAD_TRACK

MAIN_LOOP_END:
	CALL	FLUSH_KEYS
	JP	START_EXIT

; Drain any pending console input (e.g. Esc) before returning to CP/M.
FLUSH_KEYS:
	LD	C, $06
	LD	E, $FF
FLUSH_KEYS_LOOP:
	CALL	BDOS
	OR	A
	JR	NZ, FLUSH_KEYS_LOOP
	RET

; Print pause/loop status queued by key handler; runs after WAITQ only.
PRINT_DEFERRED_STATUS:
	LD	A, (STATUS_MSG_PENDING)
	OR	A
	RET	Z
	PUSH	AF
	XOR	A
	LD	(STATUS_MSG_PENDING), A
	POP	AF
	CP	STATUS_PLAYING
	JR	Z, PDS_PLAYING
	CP	STATUS_PAUSED
	JR	Z, PDS_PAUSED
	CP	STATUS_LOOP_PLAYLIST
	JR	Z, PDS_LOOP_PLAYLIST
	CP	STATUS_LOOP_TRACK
	JR	Z, PDS_LOOP_TRACK
	LD	DE, MSG_LOOP_OFF
	JR	PDS_EMIT
PDS_LOOP_TRACK:
	LD	DE, MSG_LOOP_TRACK
	JR	PDS_EMIT
PDS_LOOP_PLAYLIST:
	LD	DE, MSG_LOOP_PLAYLIST
	JR	PDS_EMIT
PDS_PAUSED:
	LD	DE, MSG_STATE_PAUSED
	JR	PDS_EMIT
PDS_PLAYING:
	LD	DE, MSG_STATE_PLAYING
PDS_EMIT:
	CALL	PRTSTR
	JP	CRLF

; Reload the track selected by TRACK_SELECTED from TRACK_LIST.
; Rebuilds FCB_WORK from the track name, reinits engine, re-enters main loop.
MAIN_RELOAD_TRACK:
	CALL	COPY_SELECTED_TRACK_TO_ARG
	CALL	CLASSIFY_ARG_EXTENSION
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	VALIDATE_FILE_ACCESS
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	VALIDATE_FORMAT_STRUCTURE
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	HEAP_CLEAR
	CALL	LOAD_MUSIC_FILE
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	ENGINE_INIT
	OR	A
	JP	NZ, MAIN_LOOP_END
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
	CALL	INIT_QDLY_BASE
	CALL	APPLY_ENGINE_QDLY_ADJ
	CALL	UPDATE_AUDIO_MODE_FROM_MUSIC
	CALL	CRLF
	CALL	PRINT_PLAYBACK_HW_CONFIG
	CALL	PRINT_CURRENT_TRACK_STATUS
	CALL	PRINT_AUDIO_MODE_STATUS
	LD	DE, MSG_PLAYING
	CALL	PRTSTR
	CALL	CRLF
	JP	MAIN_LOOP

; Copy TRACK_SELECTED entry from TRACK_LIST to ARG_BUFFER.
COPY_SELECTED_TRACK_TO_ARG:
	LD	A, (TRACK_SELECTED)
	LD	B, A
	LD	HL, 0
COPY_SEL_MUL:
	LD	A, B
	OR	A
	JR	Z, COPY_SEL_MUL_DONE
	DEC	B
	LD	DE, TRACK_NAME_LEN
	ADD	HL, DE
	JR	COPY_SEL_MUL
COPY_SEL_MUL_DONE:
	LD	DE, TRACK_LIST
	ADD	HL, DE
	LD	DE, ARG_BUFFER
	LD	B, TRACK_NAME_LEN
COPY_SEL_CPY:
	LD	A, (HL)
	LD	(DE), A
	INC	HL
	INC	DE
	DJNZ	COPY_SEL_CPY
	RET

PRINT_CURRENT_TRACK_STATUS:
	LD	DE, MSG_INPUT
	CALL	PRTSTR
	LD	DE, ARG_BUFFER
	CALL	PRTSTR
	CALL	CRLF
	LD	A, (FILE_ENGINE)
	CP	ENGINE_PTX
	JR	NZ, PRINT_CUR_MYM
	LD	DE, MSG_CLASS_PTX
	CALL	PRTSTR
	CALL	CRLF
	LD	A, (PTX_VARIANT)
	CP	PTX_VARIANT_PROTRACKER
	JR	Z, PRINT_CUR_PT3
	LD	DE, MSG_PTX_VARIANT_VORTEX
	CALL	PRTSTR
	CALL	CRLF
	RET
PRINT_CUR_PT3:
	LD	DE, MSG_PTX_VARIANT_PROTRACKER
	CALL	PRTSTR
	CALL	CRLF
	RET
PRINT_CUR_MYM:
	LD	DE, MSG_CLASS_MYM
	CALL	PRTSTR
	CALL	CRLF
	LD	DE, MSG_MYM_HINT_PREFIX
	CALL	PRTSTR
	LD	A, (MYM_FRAME_HINT)
	CALL	PRINT_HEX_BYTE
	JP	CRLF

; Determine runtime audio routing from loaded music content.
; PT3: enable TurboSound routing when a second embedded PT3 header exists.
; Other formats: force single-chip AY mode.
UPDATE_AUDIO_MODE_FROM_MUSIC:
	XOR	A
	LD	(AUDIO_OUT_MODE), A	; default single-chip AY
	LD	A, (FILE_ENGINE)
	CP	ENGINE_PTX
	RET	NZ
	CALL	PTX_DETECT_TURBOSOUND
	OR	A
	RET	Z
	LD	A, AUDIO_OUT_TURBOSOUND
	LD	(AUDIO_OUT_MODE), A
	RET

; Print detected hardware configuration.
PRINT_HARDWARE_CONFIG:
	LD	HL, (HW_CONFIG_DESC)
	LD	DE, HW_DESC_UNKNOWN
	LD	A, H
	OR	L
	JR	NZ, PRINT_HW_CONFIG_HAS_DESC
	EX	DE, HL
PRINT_HW_CONFIG_HAS_DESC:
	EX	DE, HL
	CALL	PRTSTR
	CALL	CRLF
	RET

; Print hardware line(s) for playback. TurboSound files show both AY port sets.
PRINT_PLAYBACK_HW_CONFIG:
	LD	A, (TSFLAG)
	OR	A
	JR	NZ, PRINT_PLAYBACK_HW_TS
	JP	PRINT_HARDWARE_CONFIG

PRINT_PLAYBACK_HW_TS:
	LD	A, (TS_DUALHW)
	OR	A
	JP	Z, PRINT_HARDWARE_CONFIG
	LD	DE, MSG_TS_HW_HDR
	CALL	PRTSTR
	CALL	CRLF
	LD	DE, MSG_TS_CHIP1_PFX
	CALL	PRTSTR
	LD	DE, (TS_DESC1)
	CALL	PRTSTR
	CALL	CRLF
	LD	DE, MSG_TS_CHIP2_PFX
	CALL	PRTSTR
	LD	DE, (TS_DESC2)
	CALL	PRTSTR
	JP	CRLF

PRINT_AUDIO_MODE_STATUS:
	LD	A, (AUDIO_OUT_MODE)
	CP	AUDIO_OUT_TURBOSOUND
	JR	Z, PRINT_AUDIO_MODE_TS
	LD	DE, MSG_AUDIO_MODE_AY
	CALL	PRTSTR
	CALL	CRLF
	RET

PRINT_AUDIO_MODE_TS:
	LD	DE, MSG_AUDIO_MODE_TS
	CALL	PRTSTR
	CALL	CRLF
	RET

; Detect TurboSound-packed PT3 footer:
; "PT3!" <off2> "PT3!" <len2> "02TS"
; On match sets TSFLAG and records TS_OFF2/TS_LEN2.
PTX_DETECT_TURBOSOUND:
	XOR	A
	LD	(TSFLAG), A
	LD	(TS_OFF2), A
	LD	(TS_OFF2+1), A
	LD	(TS_LEN2), A
	LD	(TS_LEN2+1), A
	LD	HL, (MUSIC_SIZE)
	LD	DE, 16
	OR	A
	SBC	HL, DE
	RET	C
	LD	B, H
	LD	C, L			; BC = bytes_to_scan
	LD	IX, MUSIC_BUF

PTX_TS_SCAN_LOOP:
	LD	A, (IX+0)
	CP	PT3SIG0
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+1)
	CP	PT3SIG1
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+2)
	CP	PT3SIG2
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+3)
	CP	PT3SIG3
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+6)
	CP	PT3SIG0
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+7)
	CP	PT3SIG1
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+8)
	CP	PT3SIG2
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+9)
	CP	PT3SIG3
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+12)
	CP	'0'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+13)
	CP	'2'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+14)
	CP	'T'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+15)
	CP	'S'
	JP	NZ, PTX_TS_NEXT

	LD	E, (IX+4)
	LD	D, (IX+5)		; DE = off2
	LD	L, (IX+10)
	LD	H, (IX+11)		; HL = len2
	ADD	HL, DE			; HL = off2 + len2
	LD	A, H
	OR	L
	JP	Z, PTX_TS_NEXT
	PUSH	HL
	PUSH	IX
	POP	BC
	LD	H, B
	LD	L, C
	LD	DE, MUSIC_BUF
	OR	A
	SBC	HL, DE			; HL = candidate file-relative offset
	EX	DE, HL			; DE = candidate offset
	POP	HL
	OR	A
	SBC	HL, DE
	JP	NZ, PTX_TS_NEXT

	LD	E, (IX+4)
	LD	D, (IX+5)
	LD	(TS_OFF2), DE
	LD	E, (IX+10)
	LD	D, (IX+11)
	LD	(TS_LEN2), DE
	LD	A, 1
	LD	(TSFLAG), A
	RET

PTX_TS_NEXT:
	INC	IX
	DEC	BC
	LD	A, B
	OR	C
	JP	NZ, PTX_TS_SCAN_LOOP
	XOR	A
	RET

; Milestone 9: Hardware detection and configuration
; This routine detects or configures the PSG hardware ports based on:
; 1. CLI override flags (-msx, -rc, -eb, -coleco)
; 2. HBIOS platform detection (if available)
; 3. Probing fallback (write/read register 2 test)
; 4. Defaults (MSX standard as safe fallback)
;
; Stores port configuration in PSG_REG_PORT, PSG_DATA_PORT, PSG2_REG_PORT, PSG2_DATA_PORT.
; Stores description pointer in HW_CONFIG_DESC.
; Returns A=0 on success, A!=0 on failure.
;
DETECT_HARDWARE_CONFIG:
	CALL	CHECK_HW_CLI_FLAGS
	OR	A
	JR	NZ, DETECT_HW_TRY_HBIOS
	LD	A, 1
	LD	(PSG_HW_VALID), A
	XOR	A
	RET

DETECT_HW_TRY_HBIOS:
	CALL	DETECT_HBIOS_PLATFORM
	OR	A
	JR	NZ, DETECT_HW_TRY_PROBE
	JR	DETECT_HW_OK

DETECT_HW_TRY_PROBE:
	CALL	PROBE_HARDWARE_CONFIG
	OR	A
	JR	NZ, DETECT_HW_FALLBACK
	JR	DETECT_HW_OK

DETECT_HW_OK:
	LD	A, 1
	LD	(PSG_HW_VALID), A
	XOR	A
	RET

DETECT_HW_FALLBACK:

	CALL	SET_CONFIG_MSX
	XOR	A
	LD	(PSG_HW_VALID), A
	RET

; Apply CLI port override (-msx, -rc, -coleco, -eb). Returns A=0 if applied, A!=0 if auto.
CHECK_HW_CLI_FLAGS:
	LD	A, (HW_DETECT_MODE)
	OR	A
	JR	Z, CHECK_HW_CLI_NONE
	CP	HW_MODE_MSX
	JR	Z, CHECK_HW_CLI_MSX
	CP	HW_MODE_RC
	JR	Z, CHECK_HW_CLI_RC
	CP	HW_MODE_COLECO
	JR	Z, CHECK_HW_CLI_COLECO
	CP	HW_MODE_EB
	JR	Z, CHECK_HW_CLI_EB
CHECK_HW_CLI_NONE:
	LD	A, 1
	RET
CHECK_HW_CLI_MSX:
	CALL	SET_CONFIG_MSX
	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_RC:
	CALL	SET_CONFIG_RC
	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_COLECO:
	CALL	SET_CONFIG_COLECO
	JR	CHECK_HW_CLI_DONE
CHECK_HW_CLI_EB:
	CALL	SET_CONFIG_EB_Z180
CHECK_HW_CLI_DONE:
	XOR	A
	RET

; Detect RomWBW HBIOS and query the primary AY device ports.
; Returns A=0 on success, A!=0 on failure.
DETECT_HBIOS_PLATFORM:
	LD	HL, ($FFFC)		; HL := pointer to HBIOS ident
	LD	A, 'W'
	CP	(HL)
	RET	NZ
	INC	HL
	LD	A, ~'W'
	CP	(HL)
	RET	NZ

	LD	B, BF_SYSVER
	LD	C, 0
	RST	08			; L := platform id
	LD	A, L
	LD	(HBIOS_PLATFORM_ID), A

	LD	BC, BC_SYSGET_SNDCNT
	RST	08
	LD	A, E
	OR	A
	RET	NZ			; No sound devices reported

	XOR	A
	LD	C, A			; Query sound unit 0
	LD	B, BF_SNDQUERY
	LD	E, BF_SNDQ_DEV
	RST	08
	OR	A
	RET	NZ

	; D=RSEL, E=RDAT from HBIOS query-dev
	LD	A, D
	LD	(PSG_REG_PORT), A
	LD	A, E
	LD	(PSG_DATA_PORT), A
	LD	A, D
	LD	(PSG2_REG_PORT), A
	LD	A, E
	LD	(PSG2_DATA_PORT), A
	CALL	SET_HW_DESC_FROM_RSEL
	LD	A, HW_MODE_AUTO
	LD	(HW_DETECT_MODE), A
	CALL	APPLY_Z180_FOR_PLATFORM
	XOR	A
	RET

; Map HBIOS platform id to Z180 I/O base (tune.com CFGTBL Z180 column).
APPLY_Z180_FOR_PLATFORM:
	LD	A, (HBIOS_PLATFORM_ID)
	LD	HL, HW_Z180_PLT_TBL
APPLY_Z180_LOOP:
	CP	(HL)
	JR	Z, APPLY_Z180_FOUND
	INC	HL
	LD	A, (HL)
	CP	$FF
	JR	Z, APPLY_Z180_NONE
	INC	HL
	LD	A, (HBIOS_PLATFORM_ID)
	JR	APPLY_Z180_LOOP
APPLY_Z180_NONE:
	LD	A, $FF
	LD	(Z180_IO_BASE), A
	RET
APPLY_Z180_FOUND:
	INC	HL
	LD	A, (HL)
	LD	(Z180_IO_BASE), A
	RET

; Map a known RSEL port to a human-readable hardware description.
; Input: A=RSEL port. Preserves BC/DE/HL.
SET_HW_DESC_FROM_RSEL:
	PUSH	AF
	CP	$A0
	JR	Z, SET_HW_DESC_MSX
	CP	$A1
	JR	Z, SET_HW_DESC_MSX
	CP	$D8
	JR	Z, SET_HW_DESC_RC
	CP	$68
	JR	Z, SET_HW_DESC_Z180
	CP	$51
	JR	Z, SET_HW_DESC_COLECO
	LD	HL, HW_DESC_HBIOS
	JR	SET_HW_DESC_STORE
SET_HW_DESC_MSX:
	LD	HL, HW_DESC_MSX
	JR	SET_HW_DESC_STORE
SET_HW_DESC_RC:
	LD	HL, HW_DESC_EB_RC
	JR	SET_HW_DESC_STORE
SET_HW_DESC_Z180:
	LD	HL, HW_DESC_EB_Z180
	JR	SET_HW_DESC_STORE
SET_HW_DESC_COLECO:
	LD	HL, HW_DESC_COLECO
SET_HW_DESC_STORE:
	LD	(HW_CONFIG_DESC), HL
	POP	AF
	RET

; Probe hardware to determine PSG presence and configuration.
; Tries common port triples and tests each with a Tune-compatible probe.
; Returns A=0 on success (config set), A!=0 on failure.
PROBE_HARDWARE_CONFIG:
	; Z180 EB ($68/$60/$68) before RC/MSX to avoid false positives on SCZ180
	LD	B, $68			; RSEL
	LD	C, $60			; RDAT
	LD	D, $68			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_Z180

	LD	B, $A0			; MSX RSEL
	LD	C, $A1			; RDAT
	LD	D, $A2			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_MSX

	LD	B, $D8			; RC/EB RSEL
	LD	C, $D0			; RDAT
	LD	D, $D8			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_RC

	LD	B, $51			; Coleco RSEL
	LD	C, $50			; RDAT
	LD	D, $52			; RIN
	CALL	PROBE_AY_PORTS
	OR	A
	JR	Z, PROBE_HW_SET_COLECO

	LD	A, 1
	RET

PROBE_HW_SET_MSX:
	CALL	SET_CONFIG_MSX
	JR	PROBE_SUCCESS
PROBE_HW_SET_RC:
	CALL	SET_CONFIG_RC
	JR	PROBE_SUCCESS
PROBE_HW_SET_Z180:
	CALL	SET_CONFIG_EB_Z180
	JR	PROBE_SUCCESS
PROBE_HW_SET_COLECO:
	CALL	SET_CONFIG_COLECO
	JR	PROBE_SUCCESS

PROBE_SUCCESS:
	XOR	A
	RET

; Undo probe side effects on port pair BC (RSEL, RDAT): mixer off, amps down.
; Do not write tone period registers (0 = max pitch).
; Input: B=RSEL, C=RDAT.
PROBE_AY_QUIET:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	LD	A, B
	LD	E, A			; E = RSEL (preserve for slow-IO exit)
	LD	A, C
	LD	D, A			; D = RDAT
	LD	A, E
	CP	$68
	JR	Z, PROBE_AY_QUIET_SLOW
	CP	$D8
	JR	Z, PROBE_AY_QUIET_SLOW
	JR	PROBE_AY_QUIET_IO
PROBE_AY_QUIET_SLOW:
	CALL	PSG_IO_SLOW_ENTER
PROBE_AY_QUIET_IO:
	LD	B, 0
	LD	C, E
	LD	A, 7
	OUT	(C), A
	LD	C, D
	LD	A, $3F
	OUT	(C), A
	LD	C, E
	LD	A, 8
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	LD	C, E
	LD	A, 9
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	LD	C, E
	LD	A, 10
	OUT	(C), A
	LD	C, D
	LD	A, $00
	OUT	(C), A
	LD	A, E
	CP	$68
	JR	Z, PROBE_AY_QUIET_SLOWX
	CP	$D8
	JR	Z, PROBE_AY_QUIET_SLOWX
	JR	PROBE_AY_QUIET_DONE
