; Tune-compatible AY probe (write $AA to R2, read back via RIN).
; Input: B=RSEL, C=RDAT, D=RIN. Returns A=0 if present, A!=0 if not.
PROBE_AY_PORTS:
	PUSH	BC
	DI
	CALL	PSG_IO_SLOW_ENTER
	PUSH	DE			; preserve RIN (D)
	LD	A, B
	LD	E, A			; E := RSEL
	LD	A, C
	LD	D, A			; D := RDAT
	LD	B, 0
	LD	C, E
	LD	A, 2
	OUT	(C), A
	LD	C, D
	LD	A, $AA
	OUT	(C), A
	LD	C, E
	LD	A, 2
	OUT	(C), A
	POP	DE			; restore RIN in D
	LD	C, D
	IN	A, (C)
	CP	$AA
	LD	A, 1
	JR	NZ, PROBE_AY_DONE
	XOR	A
PROBE_AY_DONE:
	POP	BC
	CALL	PROBE_AY_QUIET
	CALL	PSG_IO_SLOW_EXIT
	EI
	RET

