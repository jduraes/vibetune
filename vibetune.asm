;-------------------------------------------------------------------------------
; MYM depacker (MYMPlay 0.4 core by Marq/Lieves!Tuore & Fit, ported from VibeTune-old).
; Unpacks one 128-frame fragment per MYM_EXTRACT call into a rotating pair of
; register windows overlaid at MUSIC_BUF; the packed file image sits at
; MYM_ROWS (2-byte row count, then packed data at MYM_DATA).
; Bit-reader state lives in the EXX bank between calls (HL' = packed pointer,
; E'/D' = bit shifter); nothing else in this build touches the EXX bank.
; MYM_EXTRACT returns IY = play position of the fragment just depacked, and
; CF=1 while more frames remain (CF=0 at end of tune).
;-------------------------------------------------------------------------------
MYM_FRAG	.EQU	128		; fragment size (frames)
MYM_REGS	.EQU	14		; PSG registers per frame
MYM_FBITS	.EQU	7		; bits per back-reference offset/length

; Bits per PSG register
MYM_REGBITS:
	.DB	8,4,8,4,8,4,5,8,5,5,5,8,8,8

MYM_INIT:
	EXX				; Starting values for MYM_READBITS
	LD	E, 1
	LD	D, 0
	LD	HL, MYM_DATA
	EXX
	LD	HL, MYM_UNCOMP + MYM_FRAG	; Starting play/depack pointers
	LD	(MYM_DEST1), HL
	LD	(MYM_DEST2), HL
	LD	(MYM_PSOURCE), HL
	LD	A, MYM_FRAG
	LD	(MYM_PLAYED), A
	LD	HL, 0
	LD	(MYM_PROWS), HL
	RET

MYM_EXTRACT:
	LD	A, 0
MYM_REGLOOP:
	PUSH	AF
	LD	C, A
	LD	B, 0
	LD	HL, MYM_REGBITS
	ADD	HL, BC
	LD	D, (HL)		; D = bits in this PSG register
	LD	HL, MYM_CURRENT
	ADD	HL, BC
	LD	E, (HL)		; E = current value of register
	LD	BC, MYM_FRAG*3
	LD	HL, (MYM_DEST1)
	LD	IX, (MYM_DEST1)	; IX = destination 1
	ADD	HL, BC
	LD	(MYM_DEST1), HL
	LD	HL, (MYM_DEST2)	; HL = destination 2
	PUSH	HL
	ADD	HL, BC
	LD	(MYM_DEST2), HL
	POP	HL
	EX	AF, AF'		; AF' = fragment end counter
	LD	A, MYM_FRAG
	EX	AF, AF'
	LD	A, 1			; Get fragment bit
	CALL	MYM_READBITS
	OR	A
	JR	NZ, MYM_COMPFRAG	; 1=compressed fragment, 0=unchanged

	LD	B, MYM_FRAG		; Unchanged fragment: just set all to E
MYM_SWEEP:
	LD	(HL), E
	INC	HL
	LD	(IX+0), E
	INC	IX
	DJNZ	MYM_SWEEP
	JP	MYM_NEXTREG

MYM_COMPFRAG:				; Compressed fragment
	LD	A, 1
	CALL	MYM_READBITS
	OR	A
	JR	NZ, MYM_NOTPREV		; 0=previous register value, 1=raw/compressed

	LD	(HL), E			; Unchanged register
	INC	HL
	LD	(IX+0), E
	INC	IX
	EX	AF, AF'
	DEC	A
	EX	AF, AF'
	JP	MYM_NEXTBIT

MYM_NOTPREV:
	LD	A, 1
	CALL	MYM_READBITS
	OR	A
	JR	Z, MYM_PACKED		; 0=compressed data, 1=raw data

	LD	A, D			; Raw data, read regbits[i] bits
	CALL	MYM_READBITS
	LD	E, A
	LD	(HL), A
	INC	HL
	LD	(IX+0), A
	INC	IX
	EX	AF, AF'
	DEC	A
	EX	AF, AF'
	JP	MYM_NEXTBIT

MYM_PACKED:
	LD	A, MYM_FBITS		; Reference to previous data: read the offset
	CALL	MYM_READBITS
	LD	C, A
	LD	A, MYM_FBITS		; Read the number of bytes
	CALL	MYM_READBITS
	LD	B, A
	PUSH	HL
	PUSH	BC
	LD	BC, -MYM_FRAG
	ADD	HL, BC
	POP	BC
	LD	A, B
	LD	B, 0
	ADD	HL, BC
	LD	B, A
	PUSH	HL
	POP	IY			; IY = source address
	POP	HL
	INC	B
MYM_COPY:
	LD	A, (IY+0)		; Copy from previous data
	INC	IY
	LD	E, A			; Set current value
	LD	(HL), A
	INC	HL
	LD	(IX+0), A
	INC	IX
	EX	AF, AF'
	DEC	A
	EX	AF, AF'
	DJNZ	MYM_COPY

MYM_NEXTBIT:
	EX	AF, AF'		; If AF'=0 then fragment is done
	LD	C, A
	EX	AF, AF'
	LD	A, C
	OR	A
	JP	NZ, MYM_COMPFRAG

MYM_NEXTREG:
	POP	AF
	LD	B, 0			; Save the current value of PSG reg
	LD	C, A
	PUSH	HL
	LD	HL, MYM_CURRENT
	ADD	HL, BC
	LD	(HL), E
	POP	HL
	INC	A			; Check if all registers are done
	CP	MYM_REGS
	JP	NZ, MYM_REGLOOP

	OR	A			; Check if dest2 must be wrapped
	LD	BC, MYM_ROWS
	SBC	HL, BC
	JR	NZ, MYM_NOWRAP

	LD	IX, MYM_UNCOMP + MYM_FRAG
	LD	HL, MYM_UNCOMP + MYM_FRAG
	LD	IY, MYM_UNCOMP + (2*MYM_FRAG)
	JR	MYM_ENDEXT

MYM_NOWRAP:
	LD	IX, MYM_UNCOMP
	LD	HL, MYM_UNCOMP + (2*MYM_FRAG)
	LD	IY, MYM_UNCOMP + MYM_FRAG

MYM_ENDEXT:
	LD	(MYM_DEST1), IX
	LD	(MYM_DEST2), HL
	LD	BC, MYM_FRAG		; Rows played so far += FRAG
	LD	HL, (MYM_PROWS)
	ADD	HL, BC
	LD	(MYM_PROWS), HL
	LD	BC, (MYM_ROWS)		; CF=1 while rows > played rows
	OR	A
	SBC	HL, BC
	RET				; CF=0 at end of tune

; Reads A bits from packed stream (EXX bank), returns bits in A
MYM_READBITS:
	EXX
	LD	B, A
	LD	C, 0
MYM_ONEBIT:
	SLA	C			; Get one bit at a time
	RRC	E
	JR	NC, MYM_NONEW		; Wrap the AND value
	LD	D, (HL)
	INC	HL
MYM_NONEW:
	LD	A, E
	AND	D
	JR	Z, MYM_ZERO
	INC	C
MYM_ZERO:
	DJNZ	MYM_ONEBIT
	LD	A, C
	EXX
	RET

;-------------------------------------------------------------------------------
; MYM engine tick. Plays one frame (14 PSG registers) from the depacked
; windows each call. When a fragment (MYM_FRAG frames) is consumed, swaps to
; the pre-depacked window and depacks the next one. Stops (silences) at end
; of tune (MYM_EXTRACT returns CF=0).
;-------------------------------------------------------------------------------
MYM_ENGINE_TICK:
	LD	A, (MYM_PLAYED)
	OR	A
	JR	NZ, MYM_TICK_FRAME
	; Fragment consumed: swap to pre-depacked window, depack the next.
	LD	HL, (MYM_NEXT_SRC)
	LD	(MYM_PSOURCE), HL
	LD	A, MYM_FRAG
	LD	(MYM_PLAYED), A
	CALL	MYM_EXTRACT
	JR	NC, MYM_TICK_STOP
	LD	(MYM_NEXT_SRC), IY
MYM_TICK_FRAME:
	; Gather 14 register bytes (stride 3*FRAG) into MYM_FRAME scratch.
	LD	HL, (MYM_PSOURCE)
	LD	DE, MYM_FRAME
	LD	B, MYM_REGS
MYM_TICK_GATHER:
	LD	A, (HL)
	LD	(DE), A
	INC	DE
	LD	BC, 3*MYM_FRAG
	ADD	HL, BC
	DJNZ	MYM_TICK_GATHER
	LD	HL, MYM_FRAME
	CALL	PSG_ROUT_BLOCK
	LD	HL, (MYM_PSOURCE)
	INC	HL
	LD	(MYM_PSOURCE), HL
	LD	A, (MYM_PLAYED)
	DEC	A
	LD	(MYM_PLAYED), A
	JP	PLAYBACK_TICK_DONE

MYM_TICK_STOP:
	CALL	PSG_SILENCE
	LD	A, PLAY_STOPPED
	LD	(PLAY_STATE), A
	JP	PLAYBACK_TICK_DONE

;===============================================================================
; Milestone 6: Main playback loop, keystroke dispatch, loop/nav state
;===============================================================================

; Main playback loop. Entered after LOAD_MUSIC_FILE succeeds.
; Each iteration: tick engine, poll key, dispatch action, frame delay.
; Exits when PLAY_STOPPED and no restart needed, or on quit.
MAIN_LOOP:
	CALL	FORCED_DLY_FRAME_BEGIN
	CALL	PLAYBACK_TICK

	; Non-blocking key poll (same as tune.com: BDOS 06h direct, E=FF).
	LD	C, $06
	LD	E, $FF
	CALL	BDOS
	OR	A
	JP	Z, MAIN_LOOP_NODELAY
	AND	$7F
	OR	A
	JP	Z, MAIN_LOOP_NODELAY

	; Key dispatch
	; Delete-arm triple press (DEL or BS) — any other key resets the count.
	CP	$7F
	JP	Z, MAIN_DEL_PRESS
	CP	$08
	JP	Z, MAIN_DEL_PRESS
	PUSH	AF
	XOR	A
	LD	(DELCNT), A
	POP	AF
	CP	KEY_QUIT
	JP	Z, MAIN_QUIT
	CP	KEY_QUIT_L
	JP	Z, MAIN_QUIT
	CP	KEY_QUIT_ESC
	JP	Z, MAIN_ESC
	CP	KEY_QUIT_CTRL_C
	JP	Z, MAIN_QUIT
	CP	KEY_PAUSE
	JP	Z, MAIN_PAUSE_TOGGLE
	CP	KEY_ENTER
	JP	Z, MAIN_ENTER_PLAY
	CP	KEY_ENTER_LF
	JP	Z, MAIN_ENTER_PLAY
	CP	KEY_NEXT
	JP	Z, MAIN_NEXT
	CP	KEY_NEXT_L
	JP	Z, MAIN_NEXT
	CP	KEY_PREV
	JP	Z, MAIN_PREV
	CP	KEY_PREV_L
	JP	Z, MAIN_PREV
	CP	KEY_LOOP
	JP	Z, MAIN_LOOP_PL_TOGGLE
	CP	KEY_LOOP_L
	JP	Z, MAIN_LOOP_TRK_TOGGLE
	CP	KEY_REDRAW
	JP	Z, MAIN_REDRAW_REQ
	CP	KEY_REDRAW_L
	JP	Z, MAIN_REDRAW_REQ
	CP	KEY_NAV_UP
	JP	Z, MAIN_NAV_UP
	CP	KEY_NAV_UP_L
	JP	Z, MAIN_NAV_UP
	CP	KEY_NAV_LEFT
	JP	Z, MAIN_NAV_LEFT
	CP	KEY_NAV_LEFT_L
	JP	Z, MAIN_NAV_LEFT
	CP	KEY_NAV_DOWN
	JP	Z, MAIN_NAV_DOWN
	CP	KEY_NAV_DOWN_L
	JP	Z, MAIN_NAV_DOWN
	CP	KEY_NAV_RIGHT
	JP	Z, MAIN_NAV_RIGHT
	CP	KEY_NAV_RIGHT_L
	JP	Z, MAIN_NAV_RIGHT
	JP	MAIN_LOOP_NODELAY

; Esc may start an arrow-key CSI (ESC [ A/B/C/D). In playlist mode always
; probe the sequence before quitting — plain -list used to treat Esc as
; immediate quit, so arrow keys never navigated (help text promised they do).
MAIN_ESC:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_ESC_QUIT		; direct-file: bare Esc quits
	CALL	UI_ESC_SEQ
	OR	A
	JR	Z, MAIN_ESC_QUIT		; bare Esc
	CP	2
	JP	Z, MAIN_DEL_PRESS	; ESC [ 3 ~ = delete key
	CP	3
	JP	Z, MAIN_ENTER_PLAY	; ESC O M = keypad Enter
	LD	A, (UI_IDXTMP)
	CP	$FF
	JP	NZ, MAIN_NAV_GO		; arrow key -> move
	JP	MAIN_LOOP_NODELAY	; other sequence — swallowed
MAIN_ESC_QUIT:
	JP	MAIN_QUIT

; Triple-DEL arms deletion of the selected track (playlist mode only).
MAIN_DEL_PRESS:
	LD	A, (TRACK_COUNT)
	OR	A
	JP	Z, MAIN_LOOP_NODELAY	; single-file mode: ignore
	LD	A, (DELCNT)
	INC	A
	LD	(DELCNT), A
	CP	3
	JP	NZ, MAIN_LOOP_NODELAY
	XOR	A
	LD	(DELCNT), A
	JP	MAIN_DELETE_ATTEMPT

; Confirm + delete the selected track file (ported from VibeTune-old
; PLAYLIST_CONFIRM_DELETE / PLAYLIST_DELETE_SELECTED).
MAIN_DELETE_ATTEMPT:
	XOR	A
	LD	(NAV_DEBOUNCE), A	; cancel any pending paused-browse reload
	; Force pause + silence while the prompt is up.
	LD	A, (PLAY_STATE)
	LD	(DEL_STATE), A
	CP	PLAY_PAUSED
	JR	Z, MAIN_DEL_PROMPT
	LD	A, PLAY_PAUSED
	LD	(PLAY_STATE), A
	CALL	PAUSE_SILENCE
MAIN_DEL_PROMPT:
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_DEL_PROMPT_PLAIN
	CALL	UI_FOOTER_STATE_ROW
	JR	C, MAIN_DEL_PROMPT_PLAIN
	PUSH	BC
	CALL	UI_CLR_ROW
	POP	BC
	LD	C, 1
	CALL	TCFG_ANSI_AT
	CALL	TCFG_COL_PRM
	JR	MAIN_DEL_PROMPT2
MAIN_DEL_PROMPT_PLAIN:
	CALL	CRLF
MAIN_DEL_PROMPT2:
	CALL	COPY_SELECTED_TRACK_TO_ARG
	LD	DE, MSG_DEL_Q1
	CALL	PRTSTR
	LD	DE, ARG_BUFFER
	CALL	PRTSTR
	LD	DE, MSG_DEL_Q2
	CALL	PRTSTR
MAIN_DEL_KEY:
	LD	C, $06
	LD	E, $FF
	CALL	BDOS
	OR	A
	JR	Z, MAIN_DEL_KEY
	AND	$7F
	CP	'y'
	JR	Z, MAIN_DEL_YES
	CP	'Y'
	JR	Z, MAIN_DEL_YES
	CP	'n'
	JR	Z, MAIN_DEL_NO
	CP	'N'
	JR	Z, MAIN_DEL_NO
	JR	MAIN_DEL_KEY
MAIN_DEL_NO:
	LD	A, (DEL_STATE)
	CP	PLAY_PLAYING
	JR	NZ, MAIN_DEL_NO2
	LD	(PLAY_STATE), A		; resume if it was playing
MAIN_DEL_NO2:
	CALL	MAIN_DEL_REDRAW_STATUS
	JP	MAIN_LOOP
MAIN_DEL_YES:
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_DEL_YES_PLAIN
	CALL	TCFG_COL_RST
	CALL	UI_FOOTER_STATE_ROW
	JR	C, MAIN_DEL_YES_PLAIN
	PUSH	BC
	CALL	UI_CLR_ROW
	POP	BC
	LD	C, 1
	CALL	TCFG_ANSI_AT
	JR	MAIN_DEL_YES2
MAIN_DEL_YES_PLAIN:
	CALL	CRLF
MAIN_DEL_YES2:
	LD	DE, MSG_DELING
	CALL	PRTSTR
	LD	DE, ARG_BUFFER
	CALL	PRTSTR
	; BDOS fn 19 (delete file) via FCB_WORK built from ARG_BUFFER
	CALL	BUILD_FCB_FROM_ARG
	OR	A
	JR	NZ, MAIN_DEL_NO		; cannot build FCB — abort quietly
	LD	DE, FCB_WORK
	LD	C, $13
	CALL	BDOS
	; Rebuild the list from disk (deleted entry disappears)
	LD	A, (DEL_STATE)		; pre-prompt play state...
	LD	(NAV_SAVED_STATE), A	; ...preserved across the slot reload
	LD	A, (TRACK_SELECTED)
	LD	(DEL_STATE), A		; reuse as scratch: desired index
	CALL	SCAN_TRACKS			; resets TRACK_COUNT/SELECTED
	LD	A, (TRACK_COUNT)
	OR	A
	JP	Z, MAIN_LOOP_END		; nothing left — exit
	; Restore the deleted slot, clamped to the new list end
	LD	B, A				; B = count
	LD	A, (DEL_STATE)
	CP	B
	JR	C, MAIN_DEL_CLAMP_OK
	LD	A, B
	DEC	A
MAIN_DEL_CLAMP_OK:
	LD	(TRACK_SELECTED), A
	LD	(TRACK_OLD), A
	CALL	UI_SHOW_PLAYLIST		; full list redraw (UI only)
	JP	MAIN_RELOAD_TRACK

; Redraw the status row after a cancelled delete prompt.
MAIN_DEL_REDRAW_STATUS:
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_DEL_RS_PLAIN
	LD	A, (PLAY_STATE)
	CP	PLAY_PAUSED
	JP	Z, UI_STATUS_PAUSED
	JP	UI_STATUS_PLAYING
MAIN_DEL_RS_PLAIN:
	LD	A, (PLAY_STATE)
	CP	PLAY_PAUSED
	JR	Z, MAIN_DEL_RS_P
	LD	DE, MSG_STATE_PLAYING
	JR	MAIN_DEL_RS_E
MAIN_DEL_RS_P:
	LD	DE, MSG_STATE_PAUSED
MAIN_DEL_RS_E:
	CALL	PRTSTR
	JP	CRLF

; Matrix navigation: marker == current track, a move switches tracks.
MAIN_NAV_UP:
	CALL	UI_NAV_UP
	JP	MAIN_NAV_GO
MAIN_NAV_LEFT:
	CALL	UI_NAV_LEFT
	JP	MAIN_NAV_GO
MAIN_NAV_DOWN:
	CALL	UI_NAV_DOWN
	JP	MAIN_NAV_GO
MAIN_NAV_RIGHT:
	CALL	UI_NAV_RIGHT
MAIN_NAV_GO:
	LD	(UI_IDXTMP), A		; UI_NAV_* clobber C; park the index
	LD	A, (TRACK_COUNT)
	OR	A
	JP	Z, MAIN_LOOP_NODELAY
	LD	A, (PLAY_STATE)	; preserve pause across the switch
	LD	(NAV_SAVED_STATE), A
	LD	A, (TRACK_SELECTED)
	LD	(TRACK_OLD), A
	LD	A, (UI_IDXTMP)
	LD	(TRACK_SELECTED), A
	JP	MAIN_NAV_RELOAD_OR_DEFER

MAIN_REDRAW_REQ:
	LD	A, (UI_ACTIVE)
	OR	A
	JP	Z, MAIN_LOOP_NODELAY
	LD	A, STATUS_REDRAW
	LD	(STATUS_MSG_PENDING), A
	JP	MAIN_LOOP_NODELAY

MAIN_QUIT:
	CALL	FORCED_DLY_FRAME_END
	CALL	FLUSH_KEYS
	CALL	UI_EXIT_TO_PROMPT
	JP	START_EXIT

MAIN_PAUSE_TOGGLE:
	LD	A, (PLAY_STATE)
	CP	PLAY_PLAYING
	JR	NZ, MAIN_RESUME
	LD	A, PLAY_PAUSED
	LD	(PLAY_STATE), A
	CALL	PAUSE_SILENCE
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_PAUSE_PLAIN
	CALL	UI_DRAW_STATE_PAUSED
	JP	MAIN_LOOP_NODELAY
MAIN_PAUSE_PLAIN:
	LD	A, STATUS_PAUSED
	LD	(STATUS_MSG_PENDING), A
	JP	MAIN_LOOP_NODELAY
MAIN_RESUME:
	CP	PLAY_PAUSED
	JP	NZ, MAIN_LOOP_NODELAY
	LD	A, (NAV_DEBOUNCE)
	OR	A
	JR	Z, MAIN_RESUME_PLAY
	; Paused browsing with a pending reload: load the selected track and play.
	XOR	A
	LD	(NAV_DEBOUNCE), A
	LD	A, PLAY_PLAYING
	LD	(NAV_SAVED_STATE), A
	JP	MAIN_RELOAD_TRACK
MAIN_RESUME_PLAY:
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_RESUME_PLAIN
	CALL	UI_DRAW_STATE_PLAYING
	JP	MAIN_LOOP_NODELAY
MAIN_RESUME_PLAIN:
	LD	A, STATUS_PLAYING
	LD	(STATUS_MSG_PENDING), A
	JP	MAIN_LOOP_NODELAY

; Enter: clear pause and play the track under '>'.
MAIN_ENTER_PLAY:
	LD	A, (TRACK_COUNT)
	OR	A
	JP	Z, MAIN_LOOP_NODELAY	; direct-file mode: ignore
	XOR	A
	LD	(NAV_DEBOUNCE), A
	LD	A, PLAY_PLAYING
	LD	(NAV_SAVED_STATE), A
	LD	(PLAY_STATE), A		; clear pause immediately
	JP	MAIN_RELOAD_TRACK

; Hard-mute both chips (TS dual / module FF/FE) or the single AY.
; PSG_MIXER_OFF only hits routed ports and leaves module chip2 sustaining.
PAUSE_SILENCE:
	JP	START_EXIT_SILENCE

MAIN_NEXT:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_NODELAY
	LD	A, (PLAY_STATE)	; preserve pause across the switch
	LD	(NAV_SAVED_STATE), A
	LD	A, (TRACK_SELECTED)
	LD	(TRACK_OLD), A
	INC	A
	LD	HL, TRACK_COUNT
	CP	(HL)
	JR	C, MAIN_NEXT_OK
	XOR	A				; wrap to 0
MAIN_NEXT_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_NAV_RELOAD_OR_DEFER

MAIN_PREV:
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_NODELAY
	LD	A, (PLAY_STATE)	; preserve pause across the switch
	LD	(NAV_SAVED_STATE), A
	LD	A, (TRACK_SELECTED)
	LD	(TRACK_OLD), A
	OR	A
	JR	NZ, MAIN_PREV_DEC
	LD	A, (TRACK_COUNT)
	DEC	A				; wrap to last
	JR	MAIN_PREV_OK
MAIN_PREV_DEC:
	DEC	A
MAIN_PREV_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_NAV_RELOAD_OR_DEFER

; Track selected by a manual nav key. Playing: reload immediately. Paused:
; move the marker only and debounce the reload ~1s (NAV_DEBOUNCE frames) so
; rapid browsing doesn't read/parse/draw every intermediate track.
MAIN_NAV_RELOAD_OR_DEFER:
	LD	A, (PLAY_STATE)
	CP	PLAY_PAUSED
	JP	NZ, MAIN_RELOAD_TRACK
	LD	A, NAV_DEBOUNCE_LEN
	LD	(NAV_DEBOUNCE), A
	CALL	UI_UPDATE_MARKER_DELTA
	JP	MAIN_LOOP_NODELAY

; 'l' toggles LOOP_TRACK, 'L' toggles LOOP_PLAYLIST (mutually exclusive).
; Plain mode keeps the deferred scrolling message; UI mode redraws the
; loop status line instead.
MAIN_LOOP_TRK_TOGGLE:
	LD	B, LOOP_TRACK
	JR	MAIN_LOOP_SET
MAIN_LOOP_PL_TOGGLE:
	LD	B, LOOP_PLAYLIST
MAIN_LOOP_SET:
	LD	A, (LOOP_MODE)
	CP	B
	JR	NZ, MAIN_LOOP_SET_NEW
	LD	B, LOOP_NONE		; same mode pressed again -> off
MAIN_LOOP_SET_NEW:
	LD	A, B
	LD	(LOOP_MODE), A
	LD	A, (UI_ACTIVE)
	OR	A
	JR	NZ, MAIN_LOOP_SET_UI
	LD	A, (LOOP_MODE)
	INC	A
	LD	(STATUS_MSG_PENDING), A
	JR	MAIN_LOOP_NODELAY
MAIN_LOOP_SET_UI:
	LD	A, STATUS_LOOP_UI
	LD	(STATUS_MSG_PENDING), A
	JR	MAIN_LOOP_NODELAY

MAIN_LOOP_NODELAY:
	CALL	WAITQ
	CALL	PRINT_DEFERRED_STATUS
	CALL	FORCED_DLY_FRAME_END

	; Paused-browse debounce: reload once the selection has settled.
	LD	A, (NAV_DEBOUNCE)
	OR	A
	JR	Z, MAIN_NO_DEBOUNCE
	DEC	A
	LD	(NAV_DEBOUNCE), A
	JP	Z, MAIN_RELOAD_TRACK
MAIN_NO_DEBOUNCE:

	; Check if stopped: handle loop/next logic
	LD	A, (PLAY_STATE)
	CP	PLAY_STOPPED
	JP	NZ, MAIN_LOOP		; still playing/paused — iterate
	LD	A, (LOOP_MODE)
	CP	LOOP_TRACK
	JP	Z, MAIN_RELOAD_CHECK
	LD	A, (TRACK_COUNT)
	OR	A
	JR	Z, MAIN_LOOP_END		; direct-file playback, no loop — exit
	; Playlist: track ended — always advance to the next track.
	LD	A, (TRACK_SELECTED)
	LD	(TRACK_OLD), A
	INC	A
	LD	HL, TRACK_COUNT
	CP	(HL)
	JR	C, MAIN_PLAYLIST_OK	; more tracks — advance
	; Last track ended: wrap to the first only when playlist-loop is on.
	LD	A, (LOOP_MODE)
	CP	LOOP_PLAYLIST
	JR	NZ, MAIN_LOOP_END
	XOR	A				; wrap to 0
MAIN_PLAYLIST_OK:
	LD	(TRACK_SELECTED), A
	JP	MAIN_RELOAD_TRACK

MAIN_LOOP_END:
	CALL	FORCED_DLY_FRAME_END
	CALL	FLUSH_KEYS
	CALL	UI_EXIT_TO_PROMPT
	JP	START_EXIT

; Drain any pending console input (e.g. Esc) before returning to CP/M.
FLUSH_KEYS:
	LD	C, $06
	LD	E, $FF
FLUSH_KEYS_LOOP:
	CALL	BDOS
	OR	A
	JR	NZ, FLUSH_KEYS_LOOP
	RET

; Print pause/loop status queued by key handler; runs after WAITQ only.
PRINT_DEFERRED_STATUS:
	LD	A, (STATUS_MSG_PENDING)
	OR	A
	RET	Z
	PUSH	AF
	XOR	A
	LD	(STATUS_MSG_PENDING), A
	POP	AF
	CP	STATUS_REDRAW
	JR	Z, PDS_REDRAW
	CP	STATUS_LOOP_UI
	JR	Z, PDS_LOOP_UI
	CP	STATUS_PLAYING
	JR	Z, PDS_PLAYING
	CP	STATUS_PAUSED
	JR	Z, PDS_PAUSED
	CP	STATUS_LOOP_PLAYLIST
	JR	Z, PDS_LOOP_PLAYLIST
	CP	STATUS_LOOP_TRACK
	JR	Z, PDS_LOOP_TRACK
	LD	DE, MSG_LOOP_OFF
	JR	PDS_EMIT
PDS_LOOP_TRACK:
	LD	DE, MSG_LOOP_TRACK
	JR	PDS_EMIT
PDS_LOOP_PLAYLIST:
	LD	DE, MSG_LOOP_PLAYLIST
	JR	PDS_EMIT
PDS_PAUSED:
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, PDS_PAUSED_PLAIN
	CALL	UI_STATUS_PAUSED
	RET
PDS_PAUSED_PLAIN:
	LD	DE, MSG_STATE_PAUSED
	JR	PDS_EMIT
PDS_PLAYING:
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, PDS_PLAYING_PLAIN
	CALL	UI_STATUS_PLAYING
	RET
PDS_PLAYING_PLAIN:
	LD	DE, MSG_STATE_PLAYING
PDS_EMIT:
	CALL	PRTSTR
	JP	CRLF
PDS_LOOP_UI:
	CALL	UI_SHOW_LOOP_STATUS
	RET
PDS_REDRAW:
	CALL	UI_FULL_REDRAW
	RET

; LOOP_TRACK: reload from disk (playlist) or re-init in memory (direct file).
MAIN_RELOAD_CHECK:
	LD	A, (TRACK_COUNT)
	OR	A
	JP	Z, MAIN_RELOAD_DIRECT
	JP	MAIN_RELOAD_TRACK

; Re-init current module in MUSIC_BUF (no disk I/O).
MAIN_RELOAD_DIRECT:
	CALL	ENGINE_INIT
	OR	A
	JP	NZ, MAIN_LOOP_END
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
	JP	MAIN_LOOP

; Reload the track selected by TRACK_SELECTED from TRACK_LIST.
; Rebuilds FCB_WORK from the track name, reinits engine, re-enters main loop.
MAIN_RELOAD_TRACK:
	CALL	FORCED_DLY_FRAME_END
	XOR	A
	LD	(NAV_DEBOUNCE), A	; no pending debounce survives a reload
	LD	(PLAY_STATE), A		; stop ticks for the duration of reload I/O
	; Instant mute on track switch: the last register state would otherwise
	; sustain on the PSG for the duration of the reload disk I/O (~300ms).
	; TS-aware; no-op if the PSG is already silent (end-of-track advance).
	CALL	START_EXIT_SILENCE
	CALL	COPY_SELECTED_TRACK_TO_ARG
	CALL	CLASSIFY_ARG_EXTENSION
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	VALIDATE_FILE_ACCESS
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	VALIDATE_FORMAT_STRUCTURE
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	HEAP_CLEAR
	CALL	LOAD_MUSIC_FILE
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	ENGINE_INIT
	OR	A
	JP	NZ, MAIN_LOOP_END
	CALL	INIT_QDLY_BASE
	CALL	APPLY_ENGINE_QDLY_ADJ
	CALL	UPDATE_AUDIO_MODE_FROM_MUSIC
	CALL	META_SNAPSHOT
	LD	A, (UI_ACTIVE)
	OR	A
	JR	Z, MAIN_RELOAD_SHOW_PLAIN
	CALL	UI_TRACK_STATUS_UPDATE
	CALL	UI_UPDATE_MARKER_DELTA
	LD	A, (NAV_SAVED_STATE)
	CP	PLAY_PAUSED
	JR	NZ, MAIN_RELOAD_SET_PLAYING
	LD	A, PLAY_PAUSED
	LD	(PLAY_STATE), A
	CALL	UI_DRAW_STATE_PAUSED
	JR	MAIN_RELOAD_STATE_OK
MAIN_RELOAD_SET_PLAYING:
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
	CALL	UI_DRAW_STATE_PLAYING
	JR	MAIN_RELOAD_STATE_OK
MAIN_RELOAD_SHOW_PLAIN:
	LD	A, (NAV_SAVED_STATE)
	CP	PLAY_PAUSED
	JR	NZ, MAIN_RELOAD_PLAYING
	LD	A, PLAY_PAUSED
	LD	(PLAY_STATE), A
	JR	MAIN_RELOAD_STATE_OK
MAIN_RELOAD_PLAYING:
	LD	A, PLAY_PLAYING
	LD	(PLAY_STATE), A
MAIN_RELOAD_STATE_OK:
	LD	A, PLAY_PLAYING
	LD	(NAV_SAVED_STATE), A	; consume: default is always play
	LD	A, (UI_ACTIVE)
	OR	A
	JP	NZ, MAIN_LOOP
	CALL	CRLF
	CALL	PRINT_TRACK_LIST	; refresh '>' marker on the new selection
	CALL	CRLF
	CALL	PRINT_INPUT_FILE_LINE
	CALL	CRLF
	CALL	PRINT_SONG_META_PLAIN
	CALL	PRINT_PLAYBACK_HW_CONFIG
	LD	A, (PLAY_STATE)
	CP	PLAY_PAUSED
	JR	Z, MAIN_RELOAD_SHOW_PAUSED
	LD	DE, MSG_STATE_PLAYING
	JR	MAIN_RELOAD_SHOW_STATE
MAIN_RELOAD_SHOW_PAUSED:
	LD	DE, MSG_STATE_PAUSED
MAIN_RELOAD_SHOW_STATE:
	CALL	PRTSTR
