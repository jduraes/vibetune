; True (A!=0) if port A lies in the Z180 internal I/O window
; [Z180_IO_BASE, Z180_IO_BASE+3Fh]. A=0 if no Z180 or port is safe.
; On SC126 IO_BASE=$C0, so $D0/$D8 (-rc) are TCR / internal — not AY.
AY_PORT_IN_Z180_WIN:
	LD	B, A
	LD	A, (Z180_IO_BASE)
	CP	$FF
	JR	Z, AY_PORT_Z180_SAFE
	LD	C, A			; C = base
	LD	A, B
	SUB	C
	JR	C, AY_PORT_Z180_SAFE	; port < base
	CP	$40
	JR	NC, AY_PORT_Z180_SAFE	; port >= base+64
	LD	A, 1
	RET
AY_PORT_Z180_SAFE:
	XOR	A
	RET

; If current PSG ports collide with Z180 internal regs, explain and abort.
; Do not remap and continue — $D0/$D8 are not usable for AY on stock SC126.
; Clobbers AF/BC/DE/HL; does not return on collision.
SANITIZE_AY_PORTS:
	LD	A, (PSG_REG_PORT)
	CALL	AY_PORT_IN_Z180_WIN
	OR	A
	JR	NZ, SANITIZE_AY_ABORT
	LD	A, (PSG_DATA_PORT)
	CALL	AY_PORT_IN_Z180_WIN
	OR	A
	RET	Z
SANITIZE_AY_ABORT:
	LD	DE, MSG_AY_Z180_COLLIDE
	CALL	PRTSTR
	CALL	CRLF
	; Park ports outside the Z180 window so exit mute cannot hit TCR/etc.
	XOR	A
	LD	(TSFLAG), A
	LD	(TS_DUALHW), A
	CALL	SET_CONFIG_MSX
	JP	START_EXIT

; Milestone 5: Load tune from FCB_WORK into MUSIC_BUF.
; FCB_WORK must already be built (BUILD_FCB_FROM_ARG called in validation).
; Reopens the file, reads 128-byte DMA blocks into MUSIC_BUF sequentially,
; stops at EOF (BDOS 14h returns non-zero) or HEAPENDB page limit.
; Stores actual loaded size (blocks * 128) in MUSIC_SIZE.
; On success: A=0, PLAY_STATE=PLAY_PLAYING.
; On open error: A=ERR_FILE_NOT_FOUND.
; On oversize: A=ERR_FILE_READ (tune exceeds heap up to HEAPENDB).
; Register use: IX=write pointer.
LOAD_MUSIC_FILE:
	; Reset FCB current-record fields before reopening
	XOR	A
	LD	(FCB_WORK+12), A	; EX = extent 0
	LD	(FCB_WORK+32), A	; CR = current record 0
	; Open file
	LD	DE, FCB_WORK
	LD	C, $0F
	CALL	BDOS
	CP	$FF
	JR	Z, LOAD_MF_NOT_FOUND
	; Setup IX = write pointer (MYM loads after the depack windows at MYM_ROWS)
	LD	IX, MUSIC_BUF
	LD	A, (FILE_ENGINE)
	CP	ENGINE_MYM
	JR	NZ, LOAD_MF_BLOCK
	LD	IX, MYM_ROWS

LOAD_MF_BLOCK:
	PUSH	IX
	POP	HL
	LD	DE, 128
	ADD	HL, DE
	LD	A, (HEAPENDB)
	CP	H
	JP	Z, LOAD_MF_OVERSIZE
	; Set DMA to IX (current write pointer)
	PUSH	IX
	POP	DE
	LD	C, $1A
	CALL	BDOS
	; Read one 128-byte sequential block
	LD	DE, FCB_WORK
	LD	C, $14
	CALL	BDOS
	OR	A
	JR	NZ, LOAD_MF_EOF	; non-zero = EOF or error
	; Advance IX by 128
	LD	DE, 128
	ADD	IX, DE
	JR	LOAD_MF_BLOCK

LOAD_MF_EOF:
	; Close file
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	; Restore default DMA before any further BDOS/console I/O (ZPM3/CP/M+).
	LD	DE, $0080
	LD	C, $1A
	CALL	BDOS
	; MUSIC_SIZE = IX - load_base (= blocks_read * 128)
	PUSH	IX
	POP	DE			; DE = current write pointer (next free block)
	LD	HL, MUSIC_BUF
	LD	A, (FILE_ENGINE)
	CP	ENGINE_MYM
	JR	NZ, LOAD_MF_SIZE
	LD	HL, MYM_ROWS
LOAD_MF_SIZE:
	LD	A, E
	SUB	L
	LD	L, A
	LD	A, D
	SBC	A, H
	LD	H, A			; HL = size in bytes (rounded to 128)
	LD	(MUSIC_SIZE), HL
	LD	A, H
	OR	L
	JR	NZ, LOAD_MF_OK
	LD	A, ERR_FILE_READ
	RET
LOAD_MF_OK:
	XOR	A
	RET

LOAD_MF_NOT_FOUND:
	LD	A, ERR_FILE_NOT_FOUND
	RET

LOAD_MF_OVERSIZE:
	LD	DE, FCB_WORK
	LD	C, $10
	CALL	BDOS
	LD	DE, $0080
	LD	C, $1A
	CALL	BDOS
	LD	A, ERR_FILE_READ
	RET

