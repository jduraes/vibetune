; tune.com PTXLP / PTxPlay.txt: SETUP bit7 or PTX_DONE when module order finishes.
; Dual TurboSound: both instances must report bit7 (old_vibetune PTXLP / TSSET1+TSSET2).
PTX_ENGINE_CHECK_END:
	LD	A, (PTX_DONE)
	OR	A
	JR	NZ, PTX_ENGINE_STOP
	LD	A, (TSFLAG)
	OR	A
	JR	Z, PTX_ENGINE_CHECK_SINGLE
	LD	A, (TS_DUALHW)
	OR	A
	JR	Z, PTX_ENGINE_CHECK_SINGLE
	LD	A, (TSSET1)
	BIT	7, A
	RET	Z
	LD	A, (TSSET2)
	BIT	7, A
	RET	Z
	JR	PTX_ENGINE_STOP
PTX_ENGINE_CHECK_SINGLE:
	LD	A, (BULBA_START + 10)
	BIT	7, A
	RET	Z
PTX_ENGINE_STOP:
	LD	A, PLAY_STOPPED
	LD	(PLAY_STATE), A
	RET

TS_PORTS_SETUP:
	LD	A, (PSG_PLAY_REG_PORT)
	LD	(TS_PORT1_RSEL), A
	LD	(TS_PORT2_RSEL), A
	LD	A, (PSG_PLAY_DATA_PORT)
	LD	(TS_PORT1_RDAT), A
	LD	(TS_PORT2_RDAT), A
	CALL	TS_ASSIGN_DESC1
	XOR	A
	LD	(TS_DUALHW), A

	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	JP	Z, TS_PORTS_SETUP_MODULE
	CP	TS_TOPO_DUALCARD
	JP	Z, TS_PORTS_CFG_DUAL

	; Auto: try a second real AY (HBIOS), then Hi-Z ⇒ module.
	CALL	TS_PORTS_TRY_DUALCARD
	LD	A, (TS_DUALHW)
	OR	A
	RET	NZ
	JP	TS_PORTS_AUTO_MODULE

; CFG dual-card: chip1 = current play ports, chip2 = CFG_AY_CARD2.
; RomWBW does not enumerate two AYs; Z180 must not guess alien pairs.
TS_PORTS_CFG_DUAL:
	LD	A, (CFG_AY_CARD2)
	OR	A
	RET	Z			; no second card configured
	CALL	AY_CARD_TO_TS2
	OR	A
	RET	NZ			; unknown / auto id
	; Refuse chip2 ports inside the Z180 internal I/O window.
	LD	A, (TS_PORT2_RSEL)
	CALL	AY_PORT_IN_Z180_WIN
	RET	NZ
	LD	A, (TS_PORT2_RDAT)
	CALL	AY_PORT_IN_Z180_WIN
	RET	NZ
	CALL	TS_ASSIGN_DESC2
	CALL	TS_VERIFY_DUAL_PORTS
	RET	NZ
	LD	A, 1
	LD	(TS_DUALHW), A
	RET

; Map CFG card id in A to TS_PORT2_*. A=0 ok, A!=0 if auto/invalid.
AY_CARD_TO_TS2:
	CP	HW_MODE_MSX
	JR	Z, AY_CARD_TS2_MSX
	CP	HW_MODE_RC
	JR	Z, AY_CARD_TS2_RC
	CP	HW_MODE_EB
	JR	Z, AY_CARD_TS2_EB
	CP	HW_MODE_COLECO
	JR	Z, AY_CARD_TS2_COLECO
	LD	A, 1
	RET
AY_CARD_TS2_MSX:
	LD	A, $A0
	LD	(TS_PORT2_RSEL), A
	LD	A, $A1
	LD	(TS_PORT2_RDAT), A
	XOR	A
	RET
AY_CARD_TS2_RC:
	LD	A, $D8
	LD	(TS_PORT2_RSEL), A
	LD	A, $D0
	LD	(TS_PORT2_RDAT), A
	XOR	A
	RET
AY_CARD_TS2_EB:
	LD	A, $68
	LD	(TS_PORT2_RSEL), A
	LD	A, $60
	LD	(TS_PORT2_RDAT), A
	XOR	A
	RET
AY_CARD_TS2_COLECO:
	LD	A, $50
	LD	(TS_PORT2_RSEL), A
	LD	A, $51
	LD	(TS_PORT2_RDAT), A
	XOR	A
	RET

; Probe HBIOS / tune-style fallback for a second distinct AY. Sets TS_DUALHW
; on success. On Z180, skip the non-readback card swap (unsafe I/O window).
TS_PORTS_TRY_DUALCARD:
	LD	HL, ($FFFC)
	LD	A, 'W'
	CP	(HL)
	JR	NZ, TS_PORTS_TRY_PROBE
	INC	HL
	LD	A, ~'W'
	CP	(HL)
	JR	NZ, TS_PORTS_TRY_PROBE

	LD	C, 1			; Query sound unit 1 (second device)
	LD	B, BF_SNDQUERY
	LD	E, BF_SNDQ_DEV
	RST	08
	OR	A
	JR	NZ, TS_PORTS_TRY_PROBE
	LD	A, B
	CP	SND_AY38910
	JR	NZ, TS_PORTS_TRY_PROBE

	LD	A, (TS_PORT1_RSEL)
	CP	D
	JR	NZ, TS_PORTS_TRY_DISTINCT
	LD	A, (TS_PORT1_RDAT)
	CP	E
	JR	Z, TS_PORTS_TRY_PROBE

TS_PORTS_TRY_DISTINCT:
	LD	A, D
	LD	(TS_PORT2_RSEL), A
	LD	A, E
	LD	(TS_PORT2_RDAT), A
	JP	TS_PORTS_SETUP_DUAL_OK

TS_PORTS_TRY_PROBE:
	; Do not assign Coleco/MSX as a phantom chip2 — that skips
	; TS_PORTS_AUTO_MODULE (FF/FE) and poisons PSG_REG_PORT on mute.
	LD	A, (HBIOS_PLATFORM_ID)
	CP	$08			; SCZ180
	RET	Z
	CP	$0A			; RCZ180
	RET	Z
	RET

; Require two distinct data ports before enabling dual-chip playback.
TS_PORTS_SETUP_DUAL_OK:
	CALL	TS_ASSIGN_DESC2
	CALL	TS_VERIFY_DUAL_PORTS
	RET	NZ
	LD	A, 1
	LD	(TS_DUALHW), A
	RET

; Auto-detect dual-AVR module: restore one port pair, Hi-Z ⇒ module dual.
; Sets TS_TOPOLOGY=MODULE so SETPORTS/SLOWIO/mute use FF/FE.
TS_PORTS_AUTO_MODULE:
	LD	A, (TS_PORT1_RSEL)
	LD	(TS_PORT2_RSEL), A
	LD	A, (TS_PORT1_RDAT)
	LD	(TS_PORT2_RDAT), A
	CALL	TS_ASSIGN_DESC2
	CALL	TSMOD_PROBE_CONFIGURED
	OR	A
	RET	Z			; readable AY → leave topology auto, dualhw=0
	LD	A, TS_TOPO_MODULE
	LD	(TS_TOPOLOGY), A
	LD	A, 1
	LD	(TS_TOPO_PROMOTED), A
	LD	(TS_DUALHW), A
	RET

; Explicit -tsm / CFG module: one port pair, both chips via 0xFF/0xFE.
;
; The module is Hi-Z on reads — HBIOS/auto detection cannot see it — so CLI
; port forces (-msx/-rc/-eb/-coleco) are normal when the build's default ports
; are wrong. Enable dual when the *configured* play ports look Hi-Z (module or
; empty). Readable AY on those ports → real chip → chip 1 only (FF/FE on a
; real AY overlays both streams). Do not shotgun-probe foreign pairs.
TS_PORTS_SETUP_MODULE:
	CALL	TS_ASSIGN_DESC2
	CALL	TSMOD_PROBE_CONFIGURED
	OR	A
	RET	Z			; readable on play ports → leave TS_DUALHW=0
	LD	A, 1
	LD	(TS_DUALHW), A
	RET

; Probe only PSG_REG_PORT/PSG_DATA_PORT. MSX also tries RIN=$A0 if $A2 fails.
; A=0 if readable AY, A!=0 if Hi-Z/empty. Clobbers BC/DE.
TSMOD_PROBE_CONFIGURED:
	LD	A, (PSG_REG_PORT)
	LD	B, A
	LD	A, (PSG_DATA_PORT)
	LD	C, A
	CALL	TSMOD_RIN_FROM_RSEL
	CALL	PROBE_AY_PORTS
	OR	A
	RET	Z
	LD	A, (PSG_REG_PORT)
	CP	$A0
	JR	NZ, TSMOD_PROBE_CFG_NONE
	LD	B, $A0
	LD	C, $A1
	LD	D, $A0			; 2-port cards: read via RSEL
	CALL	PROBE_AY_PORTS
	OR	A
	RET	Z
TSMOD_PROBE_CFG_NONE:
	OR	$FF
	RET

; Map detected RSEL to the probe RIN port (same table as PROBE_HARDWARE_CONFIG).
; Returns D = RIN. Clobbers A.
TSMOD_RIN_FROM_RSEL:
	LD	A, (PSG_REG_PORT)
	CP	$A0			; MSX
	JR	NZ, TSMOD_RIN_NOT_MSX
	LD	D, $A2
	RET
TSMOD_RIN_NOT_MSX:
	CP	$51			; Coleco
	JR	NZ, TSMOD_RIN_SAME
	LD	D, $52
	RET
TSMOD_RIN_SAME:
	LD	D, A			; EB/RC: RIN = RSEL
	RET

TS_ASSIGN_DESC1:
	LD	A, (TS_PORT1_RSEL)
	JP	TS_RSEL_TO_DESC1

TS_ASSIGN_DESC2:
	LD	A, (TS_PORT2_RSEL)
	JP	TS_RSEL_TO_DESC2

TS_RSEL_TO_DESC1:
	CALL	TS_RSEL_TO_DESC
	LD	(TS_DESC1), DE
	RET

TS_RSEL_TO_DESC2:
	CALL	TS_RSEL_TO_DESC
	LD	(TS_DESC2), DE
	RET

; Map AY register-select port in A to a description string in DE.
TS_RSEL_TO_DESC:
	CP	$A0
	JR	Z, TS_DESC_MSX
	CP	$50
	JR	Z, TS_DESC_COLECO
	CP	$51
	JR	Z, TS_DESC_COLECO
	CP	$D8
	JR	Z, TS_DESC_RC
	CP	$68
	JR	Z, TS_DESC_EB
	LD	DE, TSSTR_UNKNOWN
	RET
TS_DESC_MSX:
	LD	DE, TSSTR_MSX
	RET
TS_DESC_COLECO:
	LD	DE, TSSTR_COLECO
	RET
TS_DESC_RC:
	LD	DE, TSSTR_RC
	RET
TS_DESC_EB:
	LD	DE, TSSTR_EB
	RET

TS_VERIFY_DUAL_PORTS:
	LD	A, (TS_PORT1_RDAT)
	LD	B, A
	LD	A, (TS_PORT2_RDAT)
	CP	B
	JR	NZ, TS_VERIFY_DUAL_OK
	OR	$FF
	RET
TS_VERIFY_DUAL_OK:
	XOR	A
	RET

TS_SETPORTS1:
	LD	A, (TS_PORT1_RSEL)
	LD	(BULBA_PORTS + 0), A
	LD	A, (TS_PORT1_RDAT)
	LD	(BULBA_PORTS + 1), A
	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	JR	Z, TS_SETPORTS1_MOD
	XOR	A
	LD	(TSMOD_CURSEL), A	; dual-card: no FF/FE latch
	RET
TS_SETPORTS1_MOD:
	LD	A, (TS_PORT1_RSEL)	; module: keep PSG globals on the pair too
	LD	(PSG_REG_PORT), A
	LD	A, (TS_PORT1_RDAT)
	LD	(PSG_DATA_PORT), A
	LD	A, $FF			; chip 0; ROUT/SLOWIO latches before dump
	LD	(TSMOD_CURSEL), A
	RET

TS_SETPORTS2:
	LD	A, (TS_TOPOLOGY)
	CP	TS_TOPO_MODULE
	JR	Z, TS_SETPORTS2_MOD
	XOR	A
	LD	(TSMOD_CURSEL), A
	LD	A, (TS_PORT2_RSEL)
	LD	(BULBA_PORTS + 0), A
	LD	A, (TS_PORT2_RDAT)
	LD	(BULBA_PORTS + 1), A
	RET
TS_SETPORTS2_MOD:
	; module: same single port pair as chip 0; ROUT latches FE before dump
	LD	A, (TS_PORT1_RSEL)
	LD	(BULBA_PORTS + 0), A
	LD	(PSG_REG_PORT), A
	LD	A, (TS_PORT1_RDAT)
	LD	(BULBA_PORTS + 1), A
	LD	(PSG_DATA_PORT), A
	LD	A, $FE
	LD	(TSMOD_CURSEL), A
	RET

; Capture pristine Bulba patch bytes (+ zeroed VARS) into TS_CTXTMPL_*.
; Call once at startup before any INIT/PLAY. Template must survive HEAP_CLEAR
; (stored pre-VARS) so list-mode dual re-init cannot re-snapshot dirty self-mod.
TS_CAPTURE_PRISTINE:
	LD	HL, VARS
	XOR	A
	LD	(HL), A
	LD	DE, VARS + 1
	LD	BC, PTX_CTXSIZ - 1
	LDIR
	JP	CTX_SAVE_TMPL

TS_INIT:
	LD	A, (TS_DUALHW)
	OR	A
	RET	Z
	; Never CTX_SAVE_TMPL here: after a prior track the self-mod is dirty,
	; and HEAP_CLEAR has zeroed any heap-resident template. Always reload
	; the boot-time pristine snapshot before each chip INIT.
	CALL	TS_SETPORTS1
	CALL	TS_LOAD_TMPL
	LD	A, BULBA_SETUP_INIT
	LD	(BULBA_START + 10), A
	LD	HL, MUSIC_BUF
	CALL	BULBA_START + 3
	CALL	TS_SAVE_CTX1
	LD	A, (BULBA_START + 10)
	LD	(TSSET1), A

	CALL	TS_SETPORTS2
	CALL	TS_LOAD_TMPL
	LD	A, BULBA_SETUP_INIT
	LD	(BULBA_START + 10), A
	LD	HL, MUSIC_BUF
	LD	DE, (TS_OFF2)
	ADD	HL, DE
	CALL	BULBA_START + 3
	CALL	TS_SAVE_CTX2
	LD	A, (BULBA_START + 10)
	LD	(TSSET2), A
	RET

TS_PLAYQUARK:
	LD	A, (TS_DUALHW)
	OR	A
	RET	Z
	CALL	TS_LOAD_CTX1
	CALL	TS_SETPORTS1
	CALL	BULBA_START + 5
	CALL	TS_SAVE_CTX1
	LD	A, (BULBA_START + 10)
	LD	(TSSET1), A
	CALL	TS_LOAD_CTX2
	CALL	TS_SETPORTS2
	CALL	BULBA_START + 5
	CALL	TS_SAVE_CTX2
	LD	A, (BULBA_START + 10)
	LD	(TSSET2), A
	RET

; Hard-mute both TurboSound chips via detected port pairs (not chip-1 globals only).
TS_MUTE_BOTH_HARDWARE:
