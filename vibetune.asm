; Detect TurboSound-packed PT3 footer:
; "PT3!" <off2> "PT3!" <len2> "02TS"
; On match sets TSFLAG and records TS_OFF2/TS_LEN2.
PTX_DETECT_TURBOSOUND:
	XOR	A
	LD	(TSFLAG), A
	LD	(TS_OFF2), A
	LD	(TS_OFF2+1), A
	LD	(TS_LEN2), A
	LD	(TS_LEN2+1), A
	LD	HL, (MUSIC_SIZE)
	LD	DE, 16
	OR	A
	SBC	HL, DE
	RET	C
	LD	B, H
	LD	C, L			; BC = bytes_to_scan
	LD	IX, MUSIC_BUF

PTX_TS_SCAN_LOOP:
	LD	A, (IX+0)
	CP	PT3SIG0
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+1)
	CP	PT3SIG1
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+2)
	CP	PT3SIG2
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+3)
	CP	PT3SIG3
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+6)
	CP	PT3SIG0
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+7)
	CP	PT3SIG1
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+8)
	CP	PT3SIG2
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+9)
	CP	PT3SIG3
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+12)
	CP	'0'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+13)
	CP	'2'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+14)
	CP	'T'
	JP	NZ, PTX_TS_NEXT
	LD	A, (IX+15)
	CP	'S'
	JP	NZ, PTX_TS_NEXT

	LD	E, (IX+4)
	LD	D, (IX+5)		; DE = off2
	LD	L, (IX+10)
	LD	H, (IX+11)		; HL = len2
	ADD	HL, DE			; HL = off2 + len2
	LD	A, H
	OR	L
	JP	Z, PTX_TS_NEXT
	PUSH	HL
	PUSH	IX
	POP	BC
	LD	H, B
	LD	L, C
	LD	DE, MUSIC_BUF
	OR	A
	SBC	HL, DE			; HL = candidate file-relative offset
	EX	DE, HL			; DE = candidate offset
	POP	HL
	OR	A
	SBC	HL, DE
	JP	NZ, PTX_TS_NEXT

	LD	E, (IX+4)
	LD	D, (IX+5)
	LD	(TS_OFF2), DE
	LD	E, (IX+10)
	LD	D, (IX+11)
	LD	(TS_LEN2), DE
	LD	A, 1
	LD	(TSFLAG), A
	RET

PTX_TS_NEXT:
	INC	IX
	DEC	BC
	LD	A, B
	OR	C
	JP	NZ, PTX_TS_SCAN_LOOP
	XOR	A
	RET

; Milestone 9: Hardware detection and configuration
; Priority: 1) CLI (-msx/-rc/-eb/-coleco)  2) VTUNE.CFG primary card
;           3) HBIOS  4) probe  5) MSX default
DETECT_HARDWARE_CONFIG:
	CALL	CHECK_HW_CLI_FLAGS
	OR	A
	JR	NZ, DETECT_HW_TRY_CFG
	LD	A, 1
	LD	(PSG_HW_VALID), A
	XOR	A
	RET

DETECT_HW_TRY_CFG:
	CALL	APPLY_CFG_CARD1
	OR	A
	JR	NZ, DETECT_HW_TRY_HBIOS
	LD	A, 1
	LD	(PSG_HW_VALID), A
	XOR	A
	RET

DETECT_HW_TRY_HBIOS:
	CALL	DETECT_HBIOS_PLATFORM
	OR	A
	JR	NZ, DETECT_HW_TRY_PROBE
	JR	DETECT_HW_OK

DETECT_HW_TRY_PROBE:
	CALL	PROBE_HARDWARE_CONFIG
	OR	A
	JR	NZ, DETECT_HW_FALLBACK
	JR	DETECT_HW_OK

DETECT_HW_OK:
	LD	A, 1
	LD	(PSG_HW_VALID), A
	CALL	SANITIZE_AY_PORTS
	XOR	A
	RET

DETECT_HW_FALLBACK:

	CALL	SET_CONFIG_MSX
	CALL	APPLY_Z180_FOR_PLATFORM	; MSX ports on Z180 still need DCNTL slow-I/O
	XOR	A
	LD	(PSG_HW_VALID), A
	RET

